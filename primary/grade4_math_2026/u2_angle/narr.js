/* ==========================================================================
   第二单元 角的度量 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（5 处推翻：1 处"三条线一起亮"看不出区别 /
   2 处只讲操作不讲道理 / 1 处度数符号会念错 / 1 处钝角陷阱没进正片）。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   硬规矩：
     ① say 是念出来的话，sub 是板书字幕；
     ② act 写"绝对状态"（MOD.pm.set(40, 3)），不写"下一步"；
     ③ 答案在第 4 拍之后才出现；
     ④ 度数符号只出现在 sub：say 里一律写"90 度"（TTS 对 ° 的读法不稳定）；
     ⑤ emp 每拍 ≤1 处，只标结论词、关键数字、易错点。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 线段 / 射线 / 直线：只数端点
     --------------------------------------------------------------------- */
  const line = {
    sec: '#s-line',
    beats: SIX,
    idle: '三条线摆在一起，差别只在一个地方。点「开始讲解」。',
    lock: ['#btnLineExtend', '#btnLineReset'],
    steps: [
      { beat: '读信息',
        say: '屏幕上有三条线：线段、射线、直线。它们长得挺像，名字却不同。',
        sub: '线段 / 射线 / 直线',
        emp: [],
        act(){ M.line.set(0); } },

      { beat: '提问',
        say: '那你说，到底靠什么区分它们？是线的长短不一样吗？',
        sub: '靠什么区分这三条线？',
        emp: ['靠什么区分'],
        act(){ M.line.set(0); } },

      { beat: '找关系',
        say: '看线段：两个端点都圈出来了。端点是线的一部分，所以它到这儿就停住，不能再延长。',
        sub: '线段：2 个端点，不能延长',
        emp: ['两个端点'],
        act(){ M.line.set(1); } },

      { beat: '算一算',
        say: '射线只有一个端点，另一头没有。所以它能朝一个方向一直延伸，画都画不完。',
        sub: '射线：1 个端点，一端无限延伸',
        emp: ['一个方向'],
        act(){ M.line.set(2); } },

      { beat: '检验',
        say: '直线一头一尾都没有端点，两个方向都能无限延伸。数端点就能认出它：0 个。',
        sub: '直线：0 个端点，两端无限延伸',
        emp: ['0 个'],
        act(){ M.line.set(3); } },

      { beat: '迁移',
        say: '回头看这三条线：端点数 2、1、0，正好对应线段、射线、直线。以后先数端点，别先看长短。',
        sub: '端点 2 / 1 / 0 → 线段 / 射线 / 直线',
        emp: ['先数端点'],
        act(){ M.line.set(0); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 角的再认识：角的大小看张嘴，不看边长
     --------------------------------------------------------------------- */
  const angle = {
    sec: '#s-angle',
    beats: SIX,
    idle: '让一条边转起来，看看角是怎么变大的。点「开始讲解」。',
    lock: ['#angRange', '#btnAngReset', '#btnAngStretch', '#btnAngStretchReset'],
    steps: [
      { beat: '读信息',
        say: '角就是从一个点出发的两条射线。现在一条边不动，另一条边慢慢转起来。',
        sub: '一个顶点 + 两条射线',
        emp: [],
        act(){ M.ang.set(60); M.ang.stretch(false); } },

      { beat: '提问',
        say: '那角的大小，到底是看边画得多长，还是看两条边张开的程度？',
        sub: '看边长，还是看张开的程度？',
        emp: ['张开的程度'],
        act(){ M.ang.set(60); } },

      { beat: '找关系',
        say: '边转到两条射线互相垂直，正好张开 90 度，这就是直角。直角是分类的一把尺子。',
        sub: '90° → 直角',
        emp: ['直角'],
        act(){ M.ang.set(90); } },

      { beat: '算一算',
        say: '再往下转，两条边摊成一条直线，正好 180 度，叫平角。所以一个平角等于两个直角。',
        sub: '180° = 2 个 90°',
        emp: ['180 度'],
        act(){ M.ang.set(180); } },

      { beat: '检验',
        say: '这个角是 115 度。比 90 度大，又没摊平，所以它是钝角。分类就靠和 90、180 比。',
        sub: '115° → 钝角',
        emp: ['钝角'],
        act(){ M.ang.set(115); } },

      { beat: '迁移',
        say: '再看下面这张图：把两条边都拉长，角度一点没变，还是 75 度。角的大小只看张开的程度。',
        sub: '边拉长，角不变',
        emp: ['一点没变'],
        act(){ M.ang.set(75); M.ang.stretch(true); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 量角器：中心对顶点、0 刻度线对边、读另一边
     --------------------------------------------------------------------- */
  const measure = {
    sec: '#s-measure',
    beats: SIX,
    idle: '量角器有两圈刻度，读错一圈就会差很多。点「开始讲解」。',
    lock: ['#pmRange', '#btnPmStep', '#btnPmReset', '#btnTrap'],
    steps: [
      { beat: '读信息',
        say: '这是量角器，一个半圆，上面有两圈刻度。量角的第一步，是把它的中心对准角的顶点。',
        sub: '① 中心 对准 顶点',
        emp: ['中心'],
        act(){ M.pm.set(40, 0); } },

      { beat: '提问',
        say: '第二步要让 0 刻度线和一条边重合。可刻度有两圈，两个 0，该用哪一个？',
        sub: '两圈刻度，用哪一个 0？',
        emp: ['哪一'],
        act(){ M.pm.set(40, 1); } },

      { beat: '找关系',
        say: '记住一句话：内圈 0 在右边，外圈 0 在左边。锐角的内圈 0 对得正，就直接读内圈。',
        sub: '内圈 0 在右，外圈 0 在左',
        emp: ['内圈 0 在右'],
        act(){ M.pm.set(65, 2); } },

      { beat: '算一算',
        say: '中心对顶点，内圈 0 对准右边那条边，另一边落在 40，所以这个角是 40 度。',
        sub: '40°（读内圈）',
        emp: ['40 度'],
        act(){ M.pm.set(40, 3); } },

      { beat: '检验',
        say: '换一个钝角试试。钝角得把量角器转过来，用外圈 0：读出来是 115 度。要是错读内圈，就成了 65 度。',
        sub: '钝角读外圈：115°（不是 65°）',
        emp: ['115 度'],
        act(){ M.pm.set(115, 3); } },

      { beat: '迁移',
        say: '再看一个 150 度的角，同样是钝角、同样读外圈。判断口诀就一句：锐角读内圈，钝角读外圈。',
        sub: '锐角读内圈，钝角读外圈',
        emp: ['钝角读外圈'],
        act(){ M.pm.set(150, 3); M.trap.show(); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 画角：画射线 → 画弧 → 找点 → 连线
     --------------------------------------------------------------------- */
  const draw = {
    sec: '#s-draw',
    beats: SIX,
    idle: '要画一个 65 度的角，光有尺子不够。点「开始讲解」。',
    lock: ['#drRange', '#btnDrStep', '#btnDrAll', '#btnDrReset'],
    steps: [
      { beat: '读信息',
        say: '要画一个 65 度的角。先画一条射线 OA，A 就是这个角的顶点。',
        sub: '① 画射线 OA',
        emp: [],
        act(){ M.draw.set(0, 65); } },

      { beat: '提问',
        say: '这一条边有了，另一条边还不知道朝哪儿。怎么才能让两条边正好张开 65 度？',
        sub: '另一条边朝哪？',
        emp: ['正好张开 65 度'],
        act(){ M.draw.set(0, 65); } },

      { beat: '找关系',
        say: '以 A 为圆心画一条弧。弧上的每个点到 A 的距离都一样，这就是圆规的用处：把长度搬过去。',
        sub: '② 以 A 为圆心画弧',
        emp: ['距离都一样'],
        act(){ M.draw.set(1, 65); } },

      { beat: '算一算',
        say: '把量角器中心对准 A，在弧上找到 65 度的位置，点上点 C。角度就定在弧上了。',
        sub: '③ 弧上找 65° 的点 C',
        emp: ['点 C'],
        act(){ M.draw.set(2, 65); } },

      { beat: '检验',
        say: '连接 A 和 C，标上 65 度。画完回头量一量：中心对 A，0 刻度线对 OA，另一边正好落在 65。',
        sub: '④ 连线，标 65°',
        emp: ['正好落在 65'],
        act(){ M.draw.set(3, 65); } },

      { beat: '迁移',
        say: '换成 120 度，四步一模一样，只是量角器上找的点换了位置。方法不变，只换数。',
        sub: '换 120°：同样四步',
        emp: ['方法不变'],
        act(){ M.draw.set(3, 120); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 角的计算：平角 180 度，减掉已知的
     --------------------------------------------------------------------- */
  const calc = {
    sec: '#s-calc',
    beats: SIX,
    idle: '半圆被分成三个角，知道两个就能求第三个。点「开始讲解」。',
    lock: ['#c1Range', '#c2Range', '#btnCalcReset'],
    steps: [
      { beat: '读信息',
        say: '一条直线被两条射线分成三个角，∠1、∠2、∠3。它们合起来，正好铺满这条直线。',
        sub: '∠1 + ∠2 + ∠3 = 平角',
        emp: [],
        act(){ M.calc.set(60, 50); } },

      { beat: '提问',
        say: '平角是多少度？如果已经知道 1 和 2，第三个角还用得着量吗？',
        sub: '知道两个，还用量第三个吗？',
        emp: ['还用得着量吗'],
        act(){ M.calc.set(60, 50); } },

      { beat: '找关系',
        say: '平角是 180 度。三个角拼在这条直线上，加起来就是 180 度。这是一条可以直接用的关系。',
        sub: '∠1 + ∠2 + ∠3 = 180°',
        emp: ['180 度'],
        act(){ M.calc.set(60, 50); } },

      { beat: '算一算',
        say: '∠1 是 40 度，∠2 是 30 度，加起来 70 度。180 减 70 得 110，所以 ∠3 是 110 度。',
        sub: '∠3 = 180° − 40° − 30° = 110°',
        emp: ['110 度'],
        act(){ M.calc.set(40, 30); } },

      { beat: '检验',
        say: '回头验一遍：100 加 50 加 30，正好 180。所以不用量，减一减就能确定第三个角。',
        sub: '100° + 50° + 30° = 180° ✓',
        emp: ['正好 180'],
        act(){ M.calc.set(100, 50); } },

      { beat: '迁移',
        say: '换成 90 度和 45 度，第三个就是 45 度。只要它们还拼在这条直线上，180 这个总数就不会变。',
        sub: '90° + 45° + 45° = 180°',
        emp: ['180 这个总数'],
        act(){ M.calc.set(90, 45); } }
    ]
  };

  window.NARR = Narrator.boot([line, angle, measure, draw, calc]);
})();
