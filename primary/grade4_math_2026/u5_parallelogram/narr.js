/* ==========================================================================
   第五单元 平行四边形和梯形 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（8 处推翻：3 处内容正确性 / 2 处场景可用性 /
   3 处讲法"意义 vs 结论"）。本脚本按评审结论编写。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算（几何课=指认）→ 检验 → 迁移
   四条硬规矩：
     ① say 是"讲出来的话"（口语、短句、指认要给方位词），sub 是板书字幕；
     ② act 必须写"绝对状态"（MOD.xxx.set(80)），不能写"下一步"；
     ③ 答案在第 4 拍之后才出现，前三拍只摆已知条件（不剧透）；
     ④ emp 标重读，每拍 ≤1 处，只标结论词/关键数字/易错点，必须逐字出现在 say 里。
   几何课要点：说"这条高"时必须配 focus/reveal，否则学生不知道指哪儿。
   语音走预生成音频（晓晓），规则见 skill 的 references/voice.md。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 平行与垂直：两条直线的位置关系
     --------------------------------------------------------------------- */
  const pv = {
    sec: '#s-pv',
    beats: SIX,
    idle: '两条直线摆在一起，一共有几种关系？点「开始讲解」。',
    lock: ['#pvRange', '#btnPvReset'],
    steps: [
      { beat: '读信息',
        say: '你看画面，下面这条直线画好不动，上面这条可以移。现在离得远远的，碰不到一起。',
        sub: '直线 l 固定，直线 m 可以移动',
        emp: [],
        act(){ M.pv.set(0); } },

      { beat: '提问',
        say: '那要是把它转过来，它们会碰在一起吗？碰在一起的，还算平行吗？',
        sub: '转过来了，还平行吗？',
        emp: [],
        act(){ M.pv.set(35); } },

      { beat: '找关系',
        say: '所以只分两类：会碰在一起的叫相交，怎么延长都不碰的，叫平行。',
        sub: '两类：相交 / 不相交（平行）',
        emp: ['叫平行'],
        act(){ M.pv.set(0); } },

      { beat: '算一算',
        say: '相交里头还有一种特殊情况：正好交成直角，就叫互相垂直，这两条线互为垂线。',
        sub: '相交成直角 → <b>互相垂直</b>',
        emp: ['互相垂直'],
        act(){ M.pv.set(80); } },

      { beat: '检验',
        say: '看这一种：交叉了，可是没有直角符号，它只是相交，还不算垂直。判断要看直角，不能光靠眼睛。',
        sub: '没有直角 → 只是相交',
        emp: ['不算垂直'],
        act(){ M.pv.set(45); } },

      { beat: '迁移',
        say: '黑板的上边和下边平行，相邻两边垂直。一块黑板就是一个平面；一条在桌面、一条在墙上，不算。',
        sub: '同一平面内，才谈平行与垂直',
        emp: ['就是一个平面'],
        act(){ M.pv.set(0); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 画垂线：靠边 → 画线 → 标直角
     --------------------------------------------------------------------- */
  const drawp = {
    sec: '#s-drawp',
    beats: SIX,
    idle: '只有一把三角尺，怎么保证画出来的线一定垂直？点「开始讲解」。',
    lock: ['#btnDpStep', '#btnDpAll', '#btnDpReset'],
    steps: [
      { beat: '读信息',
        say: '直线外面有一个点 P，要用三角尺过这个点，画一条和直线垂直的线。',
        sub: '过点 P 画 l 的垂线，工具只有三角尺',
        emp: [],
        act(){ M.dp.pick(0); M.dp.set(0); } },

      { beat: '提问',
        say: '三角尺上本来就有一个直角。它该怎么摆，才能保证画出来的线一定垂直？',
        sub: '三角尺的直角，怎么摆？',
        emp: [],
        act(){ M.dp.set(0); } },

      { beat: '找关系',
        say: '让一条直角边贴着直线，另一条直角边自然就和它垂直了。这一步叫靠边。',
        sub: '一条直角边贴 l → 另一边必垂直',
        emp: ['叫靠边'],
        act(){ M.dp.set(1); } },

      { beat: '算一算',
        say: '先靠边，再沿着另一直角边过 P 画线，最后在交点处标上直角符号。三步画完。',
        sub: '靠边 → 画线 → 标直角',
        emp: ['三步画完'],
        act(){ M.dp.set(3); } },

      { beat: '检验',
        say: '检查一下：拐角处有没有直角符号？没有符号，这条线只是看着直，不能算垂线。',
        sub: '有直角符号，才算垂线',
        emp: ['不能算垂线'],
        act(){ M.dp.set(4); } },

      { beat: '迁移',
        say: '那要是这个点正好落在直线上呢？还是同一招，把直角顶点放在点上，靠边、画线、标直角。',
        sub: '点在直线上：同一招，换个摆法',
        emp: ['还是同一招'],
        act(){ M.dp.pick(1); M.dp.set(4); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 点到直线的距离：垂线段最短
     --------------------------------------------------------------------- */
  const dist = {
    sec: '#s-dist',
    beats: SIX,
    idle: '从点 P 到直线 l 连了三条线，哪条最短？为什么是它？点「开始讲解」。',
    lock: ['#distX', '#distY', '#btnDistReset'],
    steps: [
      { beat: '读信息',
        say: '直线外面有一个点 P。从这个点向直线连了三条线，每条线旁边都标着长度。',
        sub: 'P 到 l 的三条连线，长度不同',
        emp: [],
        act(){ M.dist.set(240, 60); } },

      { beat: '提问',
        say: '这三条里有一条最短。它是碰巧最短，还是有什么道理在管着它？',
        sub: '最短的那条，是碰巧吗？',
        emp: [],
        act(){ M.dist.set(240, 120); } },

      { beat: '找关系',
        say: '最短的那条，正好是垂直着落的那一条，落点处还画着一个直角符号。',
        sub: '垂着落的那条最短（绿色）',
        emp: ['垂直着落'],
        act(){ M.dist.set(240, 60); } },

      { beat: '算一算',
        say: '量一量：垂线段长 140，两条斜线分别是 184 和 178。斜着走的，都比垂直的长。',
        sub: '140 < 178 < 184',
        emp: ['都比垂直的长'],
        act(){ M.dist.set(240, 80); } },

      { beat: '检验',
        say: '把这一个点挪到别处，三个数全变了，可最短的仍然是垂直那一条。',
        sub: '换位置：最短的仍是垂线段',
        emp: ['最短的仍然'],
        act(){ M.dist.set(120, 40); } },

      { beat: '迁移',
        say: '所以量距离都得垂直着量。你想想，量身高为什么要站直、脚贴着墙？',
        sub: '距离 = 垂线段的长度',
        emp: ['垂直着量'],
        act(){ M.dist.set(330, 100); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 平行四边形：边不变，面积会变
     --------------------------------------------------------------------- */
  const para = {
    sec: '#s-para',
    beats: SIX,
    idle: '四条边都不动，只把它拉斜，面积会不会变？点「开始讲解」。',
    lock: ['#paraSkew', '#paraSide', '#btnParaReset'],
    steps: [
      { beat: '读信息',
        say: '这个平行四边形，底 20 厘米，腰 12 厘米，四条边都量好了，还画出了高。',
        sub: '底 20 厘米，腰 12 厘米',
        emp: [],
        act(){ M.para.setSide(12); M.para.setSkew(45); } },

      { beat: '提问',
        say: '把它拉斜一点，四条边的长度一个都没变。那周长变不变？面积变不变？',
        sub: '边没变，周长和面积会变吗？',
        emp: [],
        act(){ M.para.setSkew(30); } },

      { beat: '找关系',
        say: '周长是四条边加起来，边没变，周长就不变。面积是底乘高，得看高变了没有。',
        sub: '周长看边，面积看<b>高</b>',
        emp: ['得看高变了没有'],
        act(){ M.para.setSkew(70); } },

      { beat: '算一算',
        say: '底 20、高 8，面积是 20 乘 8 得 160 平方厘米；周长是 20 加 12 的和乘 2，64 厘米。',
        sub: '20 × 8 = <b>160</b>；周长 64',
        emp: ['160'],
        act(){ M.para.setSkew(45); } },

      { beat: '检验',
        say: '再压扁一点：高只剩 4，面积变成 80。周长还是 64，边没动，周长就不动。',
        sub: '高 4 → 面积 80；周长仍 64',
        emp: ['80'],
        act(){ M.para.setSkew(20); } },

      { beat: '迁移',
        say: '那要是腰从 12 缩到 7 呢？周长和面积就一起变了。长方形也是平行四边形，拉一拉就懂了。',
        sub: '腰 7：周长、面积都变',
        emp: ['一起变'],
        act(){ M.para.setSide(7); M.para.setSkew(70); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 梯形：只有一组对边平行
     --------------------------------------------------------------------- */
  const trap = {
    sec: '#s-trap',
    beats: SIX,
    idle: '有四条边，就一定是梯形吗？点「开始讲解」。',
    lock: ['button[data-t]'],
    steps: [
      { beat: '读信息',
        say: '这是一个四边形，上底 150、下底 240、高 100，都量好了。',
        sub: '上底 150，下底 240，高 100',
        emp: [],
        act(){ M.trap.pick(0); } },

      { beat: '提问',
        say: '这个图形的左下角是一个直角，看着像半个长方形。它到底还算不算梯形？',
        sub: '有直角，还算梯形吗？',
        emp: [],
        act(){ M.trap.pick(2); } },

      { beat: '找关系',
        say: '算。梯形只看对边平行：上底和下底平行，另一组对边不平行。标准就这一条。',
        sub: '标准只有一条：<b>只有一组</b>对边平行',
        emp: ['标准就这一条'],
        act(){ M.trap.pick(0); } },

      { beat: '算一算',
        say: '再看两个特殊的：两腰一样长的，叫等腰梯形；一条腰垂直两底的，叫直角梯形。',
        sub: '等腰梯形 / 直角梯形，都是梯形',
        emp: ['等腰梯形'],
        act(){ M.trap.pick(1); } },

      { beat: '检验',
        say: '反例来了：这个图形两组对边都平行。它为什么进不了梯形这一支？',
        sub: '两组都平行 → 平行四边形（反例）',
        emp: ['两组对边都平行'],
        act(){ M.trap.pick(3); } },

      { beat: '迁移',
        say: '生活里的梯子、堤坝横截面，都做成梯形。记住，只有一组对边平行，多一组都不行。',
        sub: '梯子、堤坝：只有一组对边平行',
        emp: ['只有一组对边平行'],
        act(){ M.trap.pick(2); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑥ 四边形家族图：按"几组对边平行"分类
     --------------------------------------------------------------------- */
  const tree = {
    sec: '#s-tree',
    beats: SIX,
    idle: '这一家子怎么分家？点「开始讲解」，看路径怎么亮起来。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '这张图是一个家族：最上面是四边形，往下分成几支。越往下，条件越多。',
        sub: '四边形家族：越往下，条件越多',
        emp: ['条件越多'],
        act(){ M.tree.clear(); } },

      { beat: '提问',
        say: '梯形和长方形都是四边形，它们为什么站在不同的两支里？',
        sub: '为什么它们不在同一支？',
        emp: [],
        act(){ M.tree.focus('梯形'); } },

      { beat: '找关系',
        say: '标准只有一条：几组对边平行。两组都平行的，全进平行四边形这一支。',
        sub: '两组对边都平行 → 平行四边形',
        emp: ['两组都平行的'],
        act(){ M.tree.focus('平行四边形'); } },

      { beat: '算一算',
        say: '比如正方形：它在最里面，上面是长方形，再上面是平行四边形，一路都成立。',
        sub: '正方形 → 长方形 → 平行四边形',
        emp: ['最里面'],
        act(){ M.tree.focus('正方形'); } },

      { beat: '检验',
        say: '反过来看梯形：它只有一组对边平行，它进得了平行四边形那一支吗？',
        sub: '梯形只有一组平行，进不了另一支',
        emp: ['只有一组对边平行'],
        act(){ M.tree.focus('梯形'); } },

      { beat: '迁移',
        say: '换个标准分呢？按有没有直角来分，结果就变了。所以分类之前，先说清用哪个标准。',
        sub: '标准不同，分法不同',
        emp: ['先说清'],
        act(){ M.tree.clear(); } }
    ]
  };

  window.NARR = Narrator.boot([pv, drawp, dist, para, trap, tree]);
})();
