/* ==========================================================================
   第四单元 加法模型和乘法模型 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（5 处推翻：1 处"合计一上来就显示"剧透 /
   1 处四步法只变色不给字 / 1 处旧版 attach 与新机制打架 / 2 处只讲公式不讲词义）。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   硬规矩：
     ① say 念出来、sub 板书，两者不必同字；
     ② act 写"绝对状态"（MOD.price.set(2, 1)），不写"下一步"；
     ③ 答案在第 4 拍之后才出现（第 1~3 拍把合计遮成问号）；
     ④ 数字用阿拉伯数字；"×""÷"只在 sub 里出现，say 里说"乘""除以"；
     ⑤ emp 每拍 ≤1 处。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 加法模型：部分 + 部分 = 总量
     --------------------------------------------------------------------- */
  const add = {
    sec: '#s-add',
    beats: SIX,
    idle: '两个班的人数摆在这儿，一共多少人？点「开始讲解」。',
    lock: ['#addA', '#addB', '#btnAddReset'],
    steps: [
      { beat: '读信息',
        say: '甲班 28 人，乙班 26 人。两个班的人数都摆在这儿了，可是合计那一格还是问号。',
        sub: '甲班 28 人 + 乙班 26 人 = ？',
        emp: [],
        act(){ M.add.set(28, 26, true); } },

      { beat: '提问',
        say: '两个班一共多少人？这一问，你说该用加法，还是用减法？',
        sub: '求"一共"，用加还是减？',
        emp: ['一共'],
        act(){ M.add.set(28, 26, true); } },

      { beat: '找关系',
        say: '两个部分合起来就是总量：部分加部分等于总量。所以只要问"一共"，一定用加法。',
        sub: '部分 + 部分 = 总量',
        emp: ['部分加部分等于总量'],
        act(){ M.add.set(35, 27, true); } },

      { beat: '算一算',
        say: '回到这道题。28 加 26，个位 8 加 6 得 14，写 4 进 1；十位 2 加 2 再加 1 得 5，一共 54 人。',
        sub: '28 + 26 = 54（人）',
        emp: ['54 人'],
        act(){ M.add.set(28, 26, false); } },

      { beat: '检验',
        say: '验一验：把两个班调换位置，甲班 26、乙班 28，加起来还是 54。再用减法回推，54 减 28 得 26，正好是乙班。',
        sub: '54 − 28 = 26 ✓',
        emp: ['还是 54'],
        act(){ M.add.set(26, 28, false); } },

      { beat: '迁移',
        say: '换成甲班 45 人、乙班 38 人，合起来 83 人。反过来，83 减 45 又回到 38。加减本来就是一对。',
        sub: '45 + 38 = 83；83 − 45 = 38',
        emp: ['一对'],
        act(){ M.add.set(45, 38, false); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 乘法模型一：单价 × 数量 = 总价
     --------------------------------------------------------------------- */
  const price = {
    sec: '#s-price',
    beats: SIX,
    idle: '小票上写着"总价：？"，这个问号怎么变成数？点「开始讲解」。',
    lock: ['#priceSel', '#btnPriceStep', '#btnPriceReset'],
    steps: [
      { beat: '读信息',
        say: '看这张小票：校服，单价 120 元一套，数量 5 套。总价那一行，还是个问号。',
        sub: '单价 120 元/套，数量 5 套',
        emp: [],
        act(){ M.price.set(2, 0); } },

      { beat: '提问',
        say: '这个问号该怎么变成数？先想一件事：总价到底是什么意思？',
        sub: '总价是什么意思？',
        emp: ['总价到底是什么意思'],
        act(){ M.price.set(2, 0); } },

      { beat: '找关系',
        say: '总价就是"一共要花多少钱"。一套 120，买 5 套，就是 5 个 120。所以单价乘数量等于总价。',
        sub: '单价 × 数量 = 总价',
        emp: ['5 个 120'],
        act(){ M.price.set(2, 1); } },

      { beat: '算一算',
        say: '把数代进去：120 乘 5 等于 600。写答案要带单位，所以是 600 元。',
        sub: '120 × 5 = 600（元）',
        emp: ['600 元'],
        act(){ M.price.set(2, 2); } },

      { beat: '检验',
        say: '把 600 填回小票，小票就完整了。反着算一遍：600 除以 5 得 120，正好回到单价。',
        sub: '600 ÷ 5 = 120 ✓',
        emp: ['小票就完整了'],
        act(){ M.price.set(2, 3); } },

      { beat: '迁移',
        say: '再看这箱粉笔：总价 840 元，4 箱，这回求单价。要用除法，840 除以 4 得 210 元一箱。',
        sub: '840 ÷ 4 = 210（元/箱）',
        emp: ['要用除法'],
        act(){ M.price.set(3, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 乘法模型二：速度 × 时间 = 路程
     --------------------------------------------------------------------- */
  const speed = {
    sec: '#s-speed',
    beats: SIX,
    idle: '速度 60 千米每时，走 3 小时，能走多远？点「开始讲解」。',
    lock: ['#spdV', '#spdT', '#btnSpdReset'],
    steps: [
      { beat: '读信息',
        say: '速度 60 千米每时，走了 3 小时。这里的"每时"，就是每一个小时。',
        sub: '60 千米/时，走 3 小时',
        emp: ['每一个小时'],
        act(){ M.spd.set(60, 3); } },

      { beat: '提问',
        say: '那一共走了多远？三个小时，是不是就把速度乘三？',
        sub: '一共走多远？',
        emp: ['走了多远'],
        act(){ M.spd.set(60, 3); } },

      { beat: '找关系',
        say: '先只想 1 小时：速度 60，1 小时就走 60 千米。这就是"每时"的意思，一个小时的份。',
        sub: '1 小时走 60 千米',
        emp: ['一个小时的份'],
        act(){ M.spd.set(60, 1); } },

      { beat: '算一算',
        say: '3 小时就是 3 个 60，也就是 3 份。60 乘 3 等于 180，所以路程是 180 千米。',
        sub: '60 × 3 = 180（千米）',
        emp: ['3 份'],
        act(){ M.spd.set(60, 3); } },

      { beat: '检验',
        say: '换一组验：80 千米每时走 5 小时，5 个 80 是 400 千米。反过来 400 除以 5 得 80，对得上。',
        sub: '80 × 5 = 400；400 ÷ 5 = 80 ✓',
        emp: ['对得上'],
        act(){ M.spd.set(80, 5); } },

      { beat: '迁移',
        say: '40 千米每时走 6 小时，就是 240 千米。速度乘时间永远是路程，换成除法就是求速度或求时间。',
        sub: '40 × 6 = 240（千米）',
        emp: ['永远是路程'],
        act(){ M.spd.set(40, 6); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 模型辨析：四步法
     --------------------------------------------------------------------- */
  const judge = {
    sec: '#s-judge',
    beats: SIX,
    idle: '拿到一道题，先别急着算。点「开始讲解」。',
    lock: ['#btnJudgeNext', '#btnJudgeShow', '#btnJudgeReset'],
    steps: [
      { beat: '读信息',
        say: '第一题：图书角有故事书 56 本，科技书 38 本，一共有多少本？',
        sub: '故事书 56 本，科技书 38 本',
        emp: [],
        act(){ M.judge.set(0, 0); } },

      { beat: '提问',
        say: '先别算。拿到一道题，你觉得第一步该做什么？',
        sub: '第一步做什么？',
        emp: ['第一步'],
        act(){ M.judge.set(0, 0); } },

      { beat: '找关系',
        say: '四步法：审题、判模型、找关系、列式。判模型就看关键词——"一共"，说明要把两部分合起来。',
        sub: '① 审题 ② 判模型 ③ 找关系 ④ 列式',
        emp: ['判模型就看关键词'],
        act(){ M.judge.set(0, 1); } },

      { beat: '算一算',
        say: '所以这是加法模型：56 加 38 等于 94 本。模型判断对了，算式自然就出来了。',
        sub: '56 + 38 = 94（本）',
        emp: ['94 本'],
        act(){ M.judge.set(0, 4); } },

      { beat: '检验',
        say: '第二题：每套 18 元，买 6 套。"每套"就是单价，这是乘法模型，18 乘 6 得 108 元。',
        sub: '18 × 6 = 108（元）',
        emp: ['乘法模型'],
        act(){ M.judge.set(1, 4); } },

      { beat: '迁移',
        say: '第四题：原来 72 本，借走 25 本。看着像减法，本质还是加法模型——总量减一部分，等于另一部分。',
        sub: '72 − 25 = 47（本）',
        emp: ['本质还是加法模型'],
        act(){ M.judge.set(3, 4); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 综合应用：两个模型一起用，分步列式
     --------------------------------------------------------------------- */
  const apply = {
    sec: '#s-apply',
    beats: SIX,
    idle: '一道题里要用两次模型，怎么排顺序？点「开始讲解」。',
    lock: ['#applySel', '#btnApplyStep', '#btnApplyReset'],
    steps: [
      { beat: '读信息',
        say: '这题有两件事：买运动鞋，买跳绳，最后问一共花多少钱。',
        sub: '运动鞋 + 跳绳 = 一共多少钱',
        emp: [],
        act(){ M.apply.set(0, 0); } },

      { beat: '提问',
        say: '一步能算完吗？如果不能，你说先算哪一步？',
        sub: '先算哪一步？',
        emp: ['先算哪一步'],
        act(){ M.apply.set(0, 0); } },

      { beat: '找关系',
        say: '先算运动鞋：48 元一双，15 双。单价乘数量，48 乘 15 等于 720 元。',
        sub: '48 × 15 = 720（元）',
        emp: ['720 元'],
        act(){ M.apply.set(0, 1); } },

      { beat: '算一算',
        say: '再算跳绳：6 元一根，30 根。6 乘 30 等于 180 元。',
        sub: '6 × 30 = 180（元）',
        emp: ['180 元'],
        act(){ M.apply.set(0, 2); } },

      { beat: '检验',
        say: '最后合起来：720 加 180 等于 900 元。回头看，前两步都是乘法，最后一步是加法。',
        sub: '720 + 180 = 900（元）',
        emp: ['前两步都是乘法'],
        act(){ M.apply.set(0, 3); } },

      { beat: '迁移',
        say: '再看牛奶那题：60 元一箱买 4 箱，付出 300 元。先算总价 240，再算找回 60。还是两步。',
        sub: '300 − 60 × 4 = 60（元）',
        emp: ['还是两步'],
        act(){ M.apply.set(2, 3); } }
    ]
  };

  window.NARR = Narrator.boot([add, price, speed, judge, apply]);
})();
