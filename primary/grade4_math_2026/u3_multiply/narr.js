/* ==========================================================================
   第三单元 多位数乘两位数 —— 课程讲解脚本
   --------------------------------------------------------------------------
   只写"讲什么 + 画面到哪一步"，语音、字幕、暂停、跳拍都由 Narrator 负责。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   四条硬规矩：
     ① say 是"讲出来的话"（口语、短句、对象感），sub 是板书字幕（短、一眼看完）；
     ② act 必须写"绝对状态"（MOD.xxx.set(2)），不能写"下一步"——否则跳拍就乱；
     ③ 答案在第 4 拍之后才出现，前三拍只摆已知条件（不剧透）；
     ④ emp 标重读，每拍 ≤1 处，只标结论词/关键数字/易错点，且必须逐字出现在 say 里。
   语音走预生成音频（晓晓），规则见 skill 的 references/voice.md。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 口算乘法：20 × 30
     --------------------------------------------------------------------- */
  const oral = {
    sec: '#s-oral',
    beats: SIX,
    idle: '20 × 30 怎么口算？点「开始讲解」，看 0 是怎么被"藏起来"的。',
    lock: ['#btnOralStep', '#oralSel'],
    steps: [
      { beat: '读信息',
        say: '你看这道题，20 乘 30。两个都是整十数，末尾都带着 0。',
        sub: '20 × 30，两个因数都是<b>整十数</b>',
        emp: [],
        act(){ M.oral.set(0); } },

      { beat: '提问',
        say: '那问题来了：末尾这个 0，一定要先算进去吗？',
        sub: '末尾那些 0，能不能先<b>放一边</b>？',
        emp: [],
        act(){ M.oral.set(0); } },

      { beat: '找关系',
        say: '不用。20 就是 2 个十，30 就是 3 个十。把十放一边，先算 2 乘 3。',
        sub: '20 是 2 个十，30 是 3 个十',
        emp: ['先算 2 乘 3'],
        act(){ M.oral.set(1); } },

      { beat: '算一算',
        say: '2 乘 3 得 6。可这个 6 不是 6 个一，是 6 个十乘十，也就是 6 个百。',
        sub: '2 × 3 = <b>6</b>　（这个 6 表示 6 个百）',
        emp: ['6 个百'],
        act(){ M.oral.set(2); } },

      { beat: '检验',
        say: '两个因数末尾一共两个 0，就在 6 后面添两个 0，得 600。回头验一下，600 除以 30 正好 20。',
        sub: '添 2 个 0 → <b>600</b>；600 ÷ 30 = 20 ✓',
        emp: ['600'],
        act(){ M.oral.set(3); } },

      { beat: '迁移',
        say: '换一道也一样。300 乘 40，先算 3 乘 4 得 12，末尾三个 0，添上三个 0，就是 12000。',
        sub: '300 × 40 → 12 → <b>12000</b>',
        emp: ['12000'],
        act(){ M.oral.pick(1); M.oral.set(3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 笔算乘法：145 × 12（竖式逐步）
     --------------------------------------------------------------------- */
  const vertical = {
    sec: '#s-vertical',
    beats: ['读信息', '提问', '找关系', '列式算①', '列式算②', '检验'],
    idle: '竖式为什么写两行？点「开始讲解」，一行一行看清楚。',
    lock: ['#btnVmStep', '#btnVmAll', '#vmSel'],
    steps: [
      { beat: '读信息',
        say: '竖式计算，145 乘 12。写竖式的时候，两个数的个位要对齐。',
        sub: '145 × 12　（<b>个位对齐</b>，从个位算起）',
        emp: ['个位要对齐'],
        act(){ M.vertical.set(0); } },

      { beat: '提问',
        say: '你有没有想过，这道题为什么要写两行？一行不行吗？',
        sub: '为什么是<b>两行</b>部分积？',
        emp: [],
        act(){ M.vertical.set(0); } },

      { beat: '找关系',
        say: '因为 12 拆开就是 10 加 2。2 要乘 145，10 也要乘 145，算两次，所以才两行。',
        sub: '12 = 10 + 2，所以要算两次',
        emp: ['算两次'],
        act(){ M.vertical.set(0); } },

      { beat: '列式算①',
        say: '先用个位上的 2 乘 145。五二得十，写 0 进 1；四二得八，加进位得 9；一二得二。第一行 290。',
        sub: '145 × <b>2</b> = <b>290</b>（进位要记得加）',
        emp: ['290'],
        act(){ M.vertical.set(3); } },

      { beat: '列式算②',
        say: '再用十位上的 1 乘 145。得到的是 145 个十，所以末尾要补一个 0，写出来 1450。',
        sub: '145 × <b>10</b> = <b>1450</b>（末尾补 0）',
        emp: ['补一个 0'],
        act(){ M.vertical.set(6); } },

      { beat: '检验',
        say: '两行加起来，290 加 1450 得 1740。回代 1740 除以 12 正好 145。最常错的，是第二行忘了补 0。',
        sub: '290 + 1450 = <b>1740</b>，回代 1740÷12=145 ✓',
        emp: ['忘了补 0'],
        act(){ M.vertical.set(10); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 因数中间或末尾有 0：25 × 40，反例 307 × 25
     --------------------------------------------------------------------- */
  const zero = {
    sec: '#s-zero',
    beats: ['读信息', '提问', '找关系', '算一算', '检验', '易错点'],
    idle: '末尾的 0 能藏，中间的 0 为什么不能藏？点「开始讲解」。',
    lock: ['#btnZeroStep', '#zeroSel'],
    steps: [
      { beat: '读信息',
        say: '25 乘 40。你注意看 40 的末尾，有一个 0。',
        sub: '25 × 40　（<b>末尾</b>有 0）',
        emp: [],
        act(){ M.zero.pick(0); M.zero.set(0); } },

      { beat: '提问',
        say: '这个 0 要不要参加计算？能不能先把它藏起来？',
        sub: '末尾的 0，能先<b>藏起来</b>吗？',
        emp: [],
        act(){ M.zero.pick(0); M.zero.set(0); } },

      { beat: '找关系',
        say: '可以。40 就是 4 乘 10。把 10 放一边，只算 25 乘 4。',
        sub: '40 = 4 × 10 → 先算 <b>25 × 4</b>',
        emp: ['只算 25 乘 4'],
        act(){ M.zero.pick(0); M.zero.set(1); } },

      { beat: '算一算',
        say: '25 乘 4 得 100。这一步口算就能出来。',
        sub: '25 × 4 = <b>100</b>',
        emp: ['100'],
        act(){ M.zero.pick(0); M.zero.set(2); } },

      { beat: '检验',
        say: '再把放一边的 10 乘回去，100 乘 10 得 1000。验一下，1000 除以 40 正好 25。',
        sub: '100 × 10 = <b>1000</b>；1000 ÷ 40 = 25 ✓',
        emp: ['1000'],
        act(){ M.zero.pick(0); M.zero.set(3); } },

      { beat: '易错点',
        say: '不过要小心，能藏起来的只有末尾的 0。看 307 乘 25，中间那个 0 占着数位，一个都不能丢。',
        sub: '307 × 25：<b>中间</b>的 0 占数位，不能藏',
        emp: ['一个都不能丢'],
        act(){ M.zero.pick(5); M.zero.set(3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 积的变化规律：12 × 5 = 60
     --------------------------------------------------------------------- */
  const law = {
    sec: '#s-law',
    beats: SIX,
    idle: '一个因数变了，积会怎么变？点「开始讲解」，看着滑块找规律。',
    lock: ['#lawRange', '#btnLawHalf', '#btnLawTriple'],
    steps: [
      { beat: '读信息',
        say: '起点是 12 乘 5 得 60。先把这个 60 记住。',
        sub: '12 × 5 = <b>60</b>（起点）',
        emp: ['60'],
        act(){ M.law.set(5); } },

      { beat: '提问',
        say: '那要是第二个因数从 5 变成 10，积会变成多少？你先猜一猜。',
        sub: '5 → 10，积会变成多少？',
        emp: [],
        act(){ M.law.set(5); } },

      { beat: '找关系',
        say: '5 变成 10，是乘 2。也就是份数翻了一倍。',
        sub: '5 → 10 = <b>× 2</b>（份数翻倍）',
        emp: ['翻了一倍'],
        act(){ M.law.set(10); } },

      { beat: '算一算',
        say: '12 乘 10 得 120。你看，积也翻了一倍，60 变成 120。',
        sub: '12 × 10 = <b>120</b>（60 也 × 2）',
        emp: ['也翻了一倍'],
        act(){ M.law.set(10); } },

      { beat: '检验',
        say: '再来一次。10 变成 20，又乘 2，积从 120 变成 240。因数乘几，积就乘几。',
        sub: '10 → 20 = × 2，积 120 → <b>240</b>',
        emp: ['积就乘几'],
        act(){ M.law.set(20); } },

      { beat: '迁移',
        say: '反过来也成立。15 是 5 的三倍，积就是 60 的三倍，180。以后算面积、算总价，用的都是这一条。',
        sub: '15 是 5 的 3 倍 → 积是 60 的 3 倍 = <b>180</b>',
        emp: ['180'],
        act(){ M.law.set(5); M.law.set(15); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 估算：302 × 21，判断 7000 元够不够
     --------------------------------------------------------------------- */
  const estimate = {
    sec: '#s-estimate',
    beats: SIX,
    idle: '不用精确算也能判断够不够？点「开始讲解」。',
    lock: ['#estSel', '#estRange'],
    steps: [
      { beat: '读信息',
        say: '每套 302 元，要买 21 套。7000 元够不够？',
        sub: '302 元 × 21 套，7000 元够吗？',
        emp: [],
        act(){ M.est.pick(0); M.est.raw(); } },

      { beat: '提问',
        say: '一定要先把 302 乘 21 精确算出来，才知道够不够吗？',
        sub: '一定要<b>精确算</b>才知道够不够吗？',
        emp: [],
        act(){ M.est.raw(); } },

      { beat: '找关系',
        say: '不一定。302 很接近 300，21 很接近 20。看成整百整十，就好算多了。',
        sub: '302 ≈ 300，21 ≈ 20',
        emp: [],
        act(){ M.est.round(); } },

      { beat: '算一算',
        say: '300 乘 20 得 6000。估一估，大约要 6000 元。',
        sub: '300 × 20 = <b>6000</b>（估算值）',
        emp: ['6000'],
        act(){ M.est.setMode(0); } },

      { beat: '检验',
        say: '可 300 和 20 都估小了，光看 6000 不好下结论。精确算得 6342，多 342，还是不到 7000，所以够。',
        sub: '6342 比 6000 多 342，还不到 7000',
        emp: ['所以够'],
        act(){ M.est.setMode(2); } },

      { beat: '迁移',
        say: '再看 198 乘 52。200 乘 50 正好一万，估出来卡在线上。精确算 10296，比一万还多，所以不够。',
        sub: '198 × 52 ≈ 10000，精确 10296 → <b>不够</b>',
        emp: ['10296'],
        act(){ M.est.pick(2); M.est.setMode(0); } }
    ]
  };

  /* 挂到页面：每个 section 一份，互不干扰 */
  window.NARR = Narrator.boot([oral, vertical, zero, law, estimate]);
})();
