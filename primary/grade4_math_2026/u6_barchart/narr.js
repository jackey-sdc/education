/* ==========================================================================
   第六单元 条形统计图 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（8 处推翻：1 处答案错误 / 2 处控件与视图不足 /
   5 处讲法"结论句 → 可操作的话"）。本脚本按评审结论编写。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   硬规矩：
     ① say 是念出来的话（口语、短句、有对象感），sub 是板书字幕（短、一眼看完）；
     ② act 必须写"绝对状态"（MOD.sc.set(5)），不能写"下一步"；
     ③ 答案在第 4 拍之后才出现，前三拍只摆已知条件（不剧透）；
     ④ say 与 sub 允许写法不同：读出来要顺口，看上去要简洁。
        · 括号写法只留在 sub，say 里写"四一班"（TTS 会把"四（1）班"念成
          "四括号一班"）
        · 数字统一用阿拉伯数字，实测 2.8 / 28 / 103 读音正确
     ⑤ emp 列出这一拍必须让人听清的重读片段（≤2 处），只标三类：
        结论词、关键数字、易错点。合成时对 emp 片段降速并前留白。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 单式条形统计图：一格代表几
     --------------------------------------------------------------------- */
  const single = {
    sec: '#s-single',
    beats: SIX,
    idle: '五组人数摆在那儿，纵轴上的一格，该代表几个人？点「开始讲解」。',
    lock: ['#scUnit', '#btnScReset'],
    steps: [
      { beat: '读信息',
        say: '你看，五个运动项目，人数分别是 28、22、18、12、6。现在要把它们画成直条。',
        sub: '28 / 22 / 18 / 12 / 6 人',
        emp: [],
        act(){ M.sc.set(1); } },

      { beat: '提问',
        say: '纵轴上的一格，画几个人？随便定一个数，行不行？',
        sub: '一格画几人，能随便定吗？',
        emp: [],
        act(){ M.sc.set(1); } },

      { beat: '找关系',
        say: '你注意看：一格代表的人越多，同一个数占的格子就越少，直条也就越矮。',
        sub: '一格代表越多 → 直条越矮',
        emp: ['越矮'],
        act(){ M.sc.set(2); } },

      { beat: '算一算',
        say: '那咱们就定：一格代表 5 人，纵轴画到 30，就够了。你看，28 人，正好 5 格多一点。',
        sub: '1 格 5 人 → 纵轴到 30',
        emp: ['5 格多一点'],
        act(){ M.sc.set(5); } },

      { beat: '检验',
        say: '要是换回一格 1 人呢？还是这 28 人，直条一下就顶到 28 格。人数一个没变，变的是格子。',
        sub: '1 格 1 人 → 顶到 28 格',
        emp: ['变的是格子'],
        act(){ M.sc.set(1); } },

      { beat: '迁移',
        say: '那要是一格 10 个人呢？28 人只剩 2.8 格。零点几格，谁读得准啊。所以一格画几个人，得挑。',
        sub: '1 格 10 人 → 2.8 格，读不准',
        emp: ['2.8 格'],
        act(){ M.sc.set(10); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 复式条形统计图：同一项目并排比高低
     --------------------------------------------------------------------- */
  const double = {
    sec: '#s-double',
    beats: SIX,
    idle: '两个班的数据，怎么放进一张图里还能比？点「开始讲解」。',
    lock: ['#btnDbStep', '#btnDbAll', '#btnDbReset'],
    steps: [
      { beat: '读信息',
        say: '两个班、五天的阅读时间都量好了。现在，要把它们放进同一张图里。',
        sub: '两个班 × 五天，放进一张图',
        emp: [],
        act(){ M.db.set(0); } },

      { beat: '提问',
        say: '先只画四一班，能比出两个班谁多谁少吗？',
        sub: '只画一个班，能比吗？',
        emp: [],
        act(){ M.db.set(1); } },

      { beat: '找关系',
        say: '要想比，就得把同一个项目的两根直条并排放。谁高，谁就多。并排站着，才比得出来。',
        sub: '同一项目并排两根，比高低',
        emp: ['并排'],
        act(){ M.db.set(3); } },

      { beat: '算一算',
        say: '比如周四这一天：四一班 30 分钟，四二班 24 分钟。并排一看，多了 6 分钟。',
        sub: '周四 30 与 24，相差 6',
        emp: ['多了 6 分钟'],
        act(){ M.db.set(5); } },

      { beat: '检验',
        say: '画完了，回头检查三件事：图例写了没有？纵轴到 30 够不够？直条有没有冒出顶？',
        sub: '图例 + 纵轴到 30 + 不超顶',
        emp: ['图例'],
        act(){ M.db.set(6); } },

      { beat: '迁移',
        say: '那要是想知道，这五天是在变多，还是变少呢？这张图就看不出来了，得换成折线统计图。',
        sub: '看变化趋势 → 折线统计图',
        emp: ['折线统计图'],
        act(){ M.db.set(2); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 数据的收集与整理：一条数据链
     --------------------------------------------------------------------- */
  const collect = {
    sec: '#s-collect',
    beats: SIX,
    idle: '全班几十个人的答案，怎么变成一张图？点「开始讲解」。',
    lock: ['#btnClStep', '#btnClReset'],
    steps: [
      { beat: '读信息',
        say: '咱们想知道，全班最喜欢吃哪种水果。一个人一个人问一圈，答案就乱成一团了。',
        sub: '问题：最喜欢吃哪种水果？',
        emp: [],
        act(){ M.cl.set(0); } },

      { beat: '提问',
        say: '大家一个一个报过来，你怎么记，才能既不漏掉、也不重复？',
        sub: '怎么记，才不漏不重？',
        emp: [],
        act(){ M.cl.set(1); } },

      { beat: '找关系',
        say: '可记下来，还是散的。得整理成统计表，一眼就能看出谁多、谁少。',
        sub: '数据散 → 整理成表',
        emp: ['统计表'],
        act(){ M.cl.set(2); } },

      { beat: '算一算',
        say: '要比高低，就把表画成条形图。你看，香蕉 18，最高；草莓 6，最矮。',
        sub: '18 最高，6 最矮',
        emp: ['条形图'],
        act(){ M.cl.set(3); } },

      { beat: '检验',
        say: '回头核对一下：表里香蕉 18、草莓 6，跟图上直条的高低，对得上吗？',
        sub: '表里的数 = 图里的高度',
        emp: [],
        act(){ M.cl.set(2); } },

      { beat: '迁移',
        say: '换成调查最喜欢的运动，或者最喜欢的一本书，还是这四步：记、整理、画、读。',
        sub: '换调查对象，四步不变',
        emp: ['四步'],
        act(){ M.cl.set(0); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 读图分析与决策：先看同一项目，再算相差
     --------------------------------------------------------------------- */
  const read = {
    sec: '#s-read',
    beats: SIX,
    idle: '同一张图，能回答哪些问题？点「开始讲解」。',
    lock: ['#btnRdStep', '#btnRdReset'],
    steps: [
      { beat: '读信息',
        say: '还是这张复式图。蓝色是四一班，橙色是四二班，横轴是周一到周五。',
        sub: '蓝＝四（1）班，橙＝四（2）班',
        emp: [],
        act(){ M.rd.set(0); } },

      { beat: '提问',
        say: '为什么非要把两个班画在一张图里？分成两张图，不是更清楚吗？',
        sub: '画一张，还是画两张？',
        emp: [],
        act(){ M.rd.set(3); } },

      { beat: '找关系',
        say: '因为同一个项目的两根直条，是并排站着的。凑在一块儿，才比得出谁多谁少。',
        sub: '同一个项目，两根直条并排',
        emp: ['并排'],
        act(){ M.rd.set(0); } },

      { beat: '算一算',
        say: '比如周四：30 减 24 等于 6。四一班多 6 分钟。',
        sub: '周四：30 − 24 = 6',
        emp: ['多 6 分钟'],
        act(){ M.rd.set(1); } },

      { beat: '检验',
        say: '只看一天可不够。五天都算一遍：5、7、2、6、2。最大的是 7，在周二。',
        sub: '5 / 7 / 2 / 6 / 2 → 最大在周二',
        emp: ['最大的是 7'],
        act(){ M.rd.set(1); M.rd.diffs(true); } },

      { beat: '迁移',
        say: '同一张图还能问别的。五天一共多少？加起来，103 分钟。问题不同，读法就不同。',
        sub: '换问法：求和 → 103 分钟',
        emp: ['103 分钟'],
        act(){ M.rd.set(2); } }
    ]
  };

  window.NARR = Narrator.boot([single, double, collect, read]);
})();
