/* ==========================================================================
   第一单元 万以上数的认识 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（6 处推翻：2 处"讲结论而不讲为什么" /
   2 处画面不动 / 1 处数字与画面不同步 / 1 处缺"改写 vs 近似"的对照）。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   硬规矩：
     ① say 是念出来的话（口语、短句、有对象感），sub 是板书字幕（短、一眼看完）；
     ② act 写"绝对状态"（MOD.place.set(5)），不写"下一步"；
     ③ 答案在第 4 拍之后才出现，前三拍只摆已知条件（不剧透）；
     ④ 数字统一用阿拉伯数字（实测 456780000 / 12561 万 / 3.2 读音正确）；
        括号只留在 sub，say 里说"十二亿"这类口语句式
     ⑤ emp 列出这一拍必须让人听清的重读片段（≤1 处），只标三类：
        结论词、关键数字、易错点。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 数位顺序表：相邻两个计数单位为什么是十倍
     --------------------------------------------------------------------- */
  const place = {
    sec: '#s-place',
    beats: SIX,
    idle: '数位顺序表从个位排到千亿位，相邻两位之间藏着同一个数。点「开始讲解」。',
    lock: ['#btnUnitDemo', '#btnUnitReset'],
    steps: [
      { beat: '读信息',
        say: '你先看这张数位顺序表。从右往左，个位、十位、百位、千位，再往上是万位、十万位，一直到亿位。',
        sub: '从右往左：个 十 百 千 万 …',
        emp: ['从右往左'],
        act(){ M.place.set(0); } },

      { beat: '提问',
        say: '那你说，相邻两个计数单位之间，到底差多少？为什么非得四位分一级？',
        sub: '相邻两个计数单位差多少？',
        emp: ['差多少'],
        act(){ M.place.set(1); } },

      { beat: '找关系',
        say: '10 个一就是 1 个十，10 个十就是 1 个百。相邻两位的进率都是 10，这就叫满十进一。',
        sub: '10 个一 = 1 个十，进率是 10',
        emp: ['满十进一'],
        act(){ M.place.set(2); } },

      { beat: '算一算',
        say: '那 10 个一万呢？就是 1 个十万。你看，万位再往左一格，就是十万位。',
        sub: '10 个一万 = 1 个十万',
        emp: ['10 个一万'],
        act(){ M.place.set(5); } },

      { beat: '检验',
        say: '反过来验一下，1 个亿里面有 10 个一千万。所以千万位往左一格就是亿位，进率还是 10。',
        sub: '1 个亿 = 10 个一千万',
        emp: ['10 个一千万'],
        act(){ M.place.set(7); } },

      { beat: '迁移',
        say: '以后不管多大的数，都靠这张表。数位越往左，单位越大，相邻两位永远是十倍。',
        sub: '越往左单位越大，相邻十倍',
        emp: ['十倍'],
        act(){ M.place.set(11); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 分级读数：先分级，再从最高级读起
     --------------------------------------------------------------------- */
  const read = {
    sec: '#s-read',
    beats: SIX,
    idle: '384562305 这一长串，怎么读才不乱？点「开始讲解」。',
    lock: ['#readNum', '#btnReadRandom', '#btnReadStep', '#btnReadAll', '#btnReadReset',
           '#writeCn', '#btnWrite', '#btnWriteClear'],
    steps: [
      { beat: '读信息',
        say: '这个数是 384562305，一共九位。一长串数字堆在一起，先别急着读。',
        sub: '384562305，九位数',
        emp: ['九位'],
        act(){ M.read.set(0, '384562305'); M.write.clear(); } },

      { beat: '提问',
        say: '从右往左每四位分一级，分出亿级、万级、个级。你想想，为什么偏偏要四位一级？',
        sub: '为什么每四位分一级？',
        emp: ['四位一级'],
        act(){ M.read.set(1, '384562305'); } },

      { beat: '找关系',
        say: '因为我们读数是"一级一级"读的。每一级都按个级的读法读，读完再加上这一级的名字。',
        sub: '一级一级读，读完加级名',
        emp: ['一级一级'],
        act(){ M.read.set(2, '384562305'); } },

      { beat: '算一算',
        say: '从最高的亿级开始：亿级是 3，读作三亿。再读万级 8456，读作八千四百五十六万。',
        sub: '3 亿 → 8456 万',
        emp: ['三亿'],
        act(){ M.read.set(3, '384562305'); } },

      { beat: '检验',
        say: '最后读个级 2305，合起来就是三亿八千四百五十六万二千三百零五。回头看，三级正好对上九位。',
        sub: '三亿八千四百五十六万二千三百零五',
        emp: ['合起来'],
        act(){ M.read.set(5, '384562305'); } },

      { beat: '迁移',
        say: '换个有零的：826000005。万级末尾的 0 不读，个级前面的 0 要读一个零，读作八亿二千六百万零五。',
        sub: '826000005 → 八亿二千六百万零五',
        emp: ['要读一个零'],
        act(){ M.read.set(5, '826000005'); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 大小比较：位数 → 最高位 → 逐位比
     --------------------------------------------------------------------- */
  const compare = {
    sec: '#s-compare',
    beats: SIX,
    idle: '5060708 和 5080607，长得像，谁大？点「开始讲解」。',
    lock: ['#cmpSel', '#btnCmp', '#btnCmpReset'],
    steps: [
      { beat: '读信息',
        say: '这两个数，5060708 和 5080607。都是七位数，长得还挺像。',
        sub: '5060708 和 5080607',
        emp: [],
        act(){ M.cmp.set(0, 0); } },

      { beat: '提问',
        say: '位数一样，那从哪一位开始比？随便挑一位比，行不行？',
        sub: '从哪一位开始比？',
        emp: ['从哪一位'],
        act(){ M.cmp.set(1, 0); } },

      { beat: '找关系',
        say: '比大小就两句话：位数多的那个数大；位数相同，就从最高位一位一位往右比。',
        sub: '位数相同 → 从最高位比',
        emp: ['从最高位'],
        act(){ M.cmp.set(2, 0); } },

      { beat: '算一算',
        say: '最高位都是 5，一样；再看下一位，0 比 8 小。所以左边小，5060708 小于 5080607。',
        sub: '5=5，0＜8 → 左边小',
        emp: ['0 比 8 小'],
        act(){ M.cmp.set(3, 0); } },

      { beat: '检验',
        say: '换一组看位数：999999 是六位，1000000 是七位。位数多的大，后面的位根本不用比。',
        sub: '999999 ＜ 1000000',
        emp: ['位数多的大'],
        act(){ M.cmp.set(0, 2); } },

      { beat: '迁移',
        say: '还有更绕的：十二亿和 120000 万。单位不一样，先化成同一个单位，其实它们是同一个数。',
        sub: '12 亿 = 120000 万',
        emp: ['同一个数'],
        act(){ M.cmp.set(3, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 数的改写：整万数去掉四个 0，用等号
     --------------------------------------------------------------------- */
  const rewrite = {
    sec: '#s-rewrite',
    beats: SIX,
    idle: '12000000 后面一长串 0，能不能少写几个？点「开始讲解」。',
    lock: ['#rwRange', '#btnRwReset'],
    steps: [
      { beat: '读信息',
        say: '这个数是 12000000，后面跟着一长串 0。读起来费劲，写起来也费劲。',
        sub: '12000000，末尾全是 0',
        emp: [],
        act(){ M.rw.set(0); } },

      { beat: '提问',
        say: '都是 0，能不能少写几个？少写之后，这个数的大小会不会变？',
        sub: '少写 0，大小会变吗？',
        emp: ['会不会变'],
        act(){ M.rw.set(1); } },

      { beat: '找关系',
        say: '末四位全是 0 的，就叫整万数。把末尾四个 0 去掉，换成一个"万"字，这就是改写。',
        sub: '末四位是 0 → 整万数',
        emp: ['整万数'],
        act(){ M.rw.set(7); } },

      { beat: '算一算',
        say: '12000000 去掉四个 0 得 1200，所以它等于 1200 万。用等号，因为大小一点没变。',
        sub: '12000000 = 1200 万',
        emp: ['1200 万'],
        act(){ M.rw.set(0); } },

      { beat: '检验',
        say: '回头看这个 8000000，去掉四个 0 是 800，就是 800 万。乘回去正好又是 8000000，对得上。',
        sub: '8000000 = 800 万 ✓',
        emp: ['对得上'],
        act(){ M.rw.set(8); } },

      { beat: '迁移',
        say: '但你看 12345678，末四位是 5678，不是 0。它不能改写，只能求近似数，那时候要用约等号。',
        sub: '末四位不是 0 → 用 ≈',
        emp: ['不能改写'],
        act(){ M.rw.set(10); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 求近似数：保留万位就看千位，满 5 进 1
     --------------------------------------------------------------------- */
  const approx = {
    sec: '#s-approx',
    beats: SIX,
    idle: '456780000 要省略到万位，看哪一位说了算？点「开始讲解」。',
    lock: ['#apRange', '#btnApW', '#btnApY', '#btnApReset'],
    steps: [
      { beat: '读信息',
        say: '这个数是 456780000，九位数。今天要做的，是把它省略到万位，或者省略到亿位。',
        sub: '456780000，省略到哪一位？',
        emp: [],
        act(){ M.ap.set(0, null); } },

      { beat: '提问',
        say: '要省略万位后面的尾数，那到底该看哪一位上的数字？看错了会怎样？',
        sub: '省略到万位，看哪一位？',
        emp: ['哪一位'],
        act(){ M.ap.set(0, null); } },

      { beat: '找关系',
        say: '四舍五入只看一位：保留到万位，就看它右边紧挨着的千位。千位满 5 就进 1，不满 5 就舍去。',
        sub: '保留万位 → 看千位：满 5 进 1',
        emp: ['满 5 就进 1'],
        act(){ M.ap.set(0, 'w'); } },

      { beat: '算一算',
        say: '看这个 125600000，千位上是 6，满 5 了，万位要进 1。所以约等于 12561 万。',
        sub: '125600000 ≈ 12561 万',
        emp: ['12561 万'],
        act(){ M.ap.set(1, 'w'); } },

      { beat: '检验',
        say: '同一个数，改成省略到亿位。这回要看千万位，千万位是 2，不满 5 全部舍去，约是 1 亿。',
        sub: '125600000 ≈ 1 亿',
        emp: ['1 亿'],
        act(){ M.ap.set(1, 'y'); } },

      { beat: '迁移',
        say: '换一个 987650000，千万位是 8，满 5 要进 1。9 亿进一位变成 10 亿，所以约是 10 亿。',
        sub: '987650000 ≈ 10 亿',
        emp: ['10 亿'],
        act(){ M.ap.set(2, 'y'); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑥ 1 亿有多大：用倍比估算，把它换成看得见的东西
     --------------------------------------------------------------------- */
  const billion = {
    sec: '#s-billion',
    beats: SIX,
    idle: '1 亿到底有多大？换成看得见的东西来量一量。点「开始讲解」。',
    lock: ['#bnBtns button'],
    steps: [
      { beat: '读信息',
        say: '1 亿到底有多大？光看数字是没感觉的。1 亿元，就是 100 万张一百元的钞票。',
        sub: '1 亿元 = 100 万张百元钞',
        emp: ['100 万张'],
        act(){ M.bn.set('money'); } },

      { beat: '提问',
        say: '你先估一估：这 100 万张钞票摞起来，能有多高？一层楼那么高，还是一座山那么高？',
        sub: '摞起来能有多高？',
        emp: ['有多高'],
        act(){ M.bn.set('money'); } },

      { beat: '找关系',
        say: '一张百元钞票大约厚 0.1 毫米，1 万张就是 1 米。1 亿是 100 万张，正好是 1 万张的 100 倍。',
        sub: '1 万张 = 1 米，1 亿是 100 倍',
        emp: ['100 倍'],
        act(){ M.bn.set('money'); } },

      { beat: '算一算',
        say: '张数是 100 倍，高度也就是 100 倍。1 米乘 100 得 100 米，比 30 米高的十层楼还高三倍多。',
        sub: '1 米 × 100 = 100 米',
        emp: ['100 米'],
        act(){ M.bn.set('rice'); } },

      { beat: '检验',
        say: '换个量验一验：1 亿秒。1 年约 3150 万秒，1 亿除以 3150 万，约是 3.2 年，比小学六年的一半还长。',
        sub: '1 亿秒 ≈ 3.2 年',
        emp: ['3.2 年'],
        act(){ M.bn.set('time'); } },

      { beat: '迁移',
        say: '你自己也能换：每步 0.5 米，1 亿步约 5000 千米，从北京走到上海都够了。方法就一个，找倍数。',
        sub: '1 亿步 ≈ 5000 千米',
        emp: ['找倍数'],
        act(){ M.bn.set('steps'); } }
    ]
  };

  window.NARR = Narrator.boot([place, read, compare, rewrite, approx, billion]);
})();
