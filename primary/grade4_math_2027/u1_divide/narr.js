/* ==========================================================================
   第一单元 除数是两位数的除法 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（5 处推翻：1 处"试商=看整十数"的口诀化 /
   1 处余数只作提醒 / 1 处商不变规律只给结论 / 1 处进一法去尾法混讲 /
   1 处口算只讲"添 0"）。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   本单元的一条主线：除法不是另一套算法，它是乘法的逆运算；
   试商、调商、商不变，全都在回答"乘几才等于它"。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 口算除法：想乘法算除法
     --------------------------------------------------------------------- */
  const oral = {
    sec: '#s-oral',
    beats: SIX,
    idle: '60 除以 20，除了数小棒还有别的想法。点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '60 除以 20。60 根小棒，每 20 根捆成一捆，正好捆成 3 捆。',
        sub: '60 里面有 3 个 20',
        emp: ['3 捆'],
        act(){ M.oral.set(6, 2, 0); } },

      { beat: '提问',
        say: '可是每算一道题都要捆一次、数一遍吗？有没有更快的想法？',
        sub: '非要数小棒吗？',
        emp: ['更快的想法'],
        act(){ M.oral.set(6, 2, 2); } },

      { beat: '找关系',
        say: '除法和乘法是一对。问 60 除以 20 得几，就是在问 20 乘几等于 60。',
        sub: '想：20 × 几 = 60',
        emp: ['20 乘几等于 60'],
        act(){ M.oral.set(6, 2, 1); } },

      { beat: '算一算',
        say: '换一道：80 除以 20。心里想 20 乘 4 等于 80，所以商就是 4。',
        sub: '80 ÷ 20 = 4',
        emp: ['商就是 4'],
        act(){ M.oral.set(8, 2, 1); } },

      { beat: '检验',
        say: '再验一道：90 除以 30，30 乘 3 等于 90，商 3 对得上。想到的乘法能验回去。',
        sub: '90 ÷ 30 = 3，30 × 3 = 90',
        emp: ['能验回去'],
        act(){ M.oral.set(9, 3, 0); } },

      { beat: '迁移',
        say: '再看几百几十除以几十：240 除以 30，去掉末尾一个 0 变成 24 除以 3，8 乘 30 正好 240，商是 8。',
        sub: '240 ÷ 30 → 24 ÷ 3 = 8',
        emp: ['去掉末尾一个 0'],
        act(){ M.oral.set(24, 3, 1); M.oral2.set(0, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 笔算除法：从高位除起，除到哪一位商写在哪一位上面
     --------------------------------------------------------------------- */
  const vertical = {
    sec: '#s-vertical',
    beats: SIX,
    idle: '425 除以 25，竖式怎么一步步写下来。点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '425 除以 25。被除数写里面，除数写左边，商要写在上面。',
        sub: '425 ÷ 25，商写在上面',
        emp: ['商要写在上面'],
        act(){ M.div.set(0, -1); } },

      { beat: '提问',
        say: '除数是两位数，能不能直接看百位上的 4，就在百位上写商？',
        sub: '能看百位吗？',
        emp: ['百位上的 4'],
        act(){ M.div.set(0, 0); } },

      { beat: '找关系',
        say: '不能。4 里连一个 25 都凑不出来，所以要连十位一起看：42 里才有一个 25。',
        sub: '42 里有 1 个 25',
        emp: ['连十位一起看'],
        act(){ M.div.set(0, 1); } },

      { beat: '算一算',
        say: '商 1 写在十位上，25 乘 1 得 25，42 减 25 余 17。落下 5 得 175，商 7。',
        sub: '25×1=25，42−25=17；175÷25=7',
        emp: ['落下 5'],
        act(){ M.div.set(1, 1); } },

      { beat: '检验',
        say: '回头看 425 除以 25 的答案 17。验算 25 乘 17 等于 425，正好；每步余数都小于 25。',
        sub: '25 × 17 = 425 ✓',
        emp: ['余数都小于 25'],
        act(){ M.div.set(0, 5); } },

      { beat: '迁移',
        say: '再换 936 除以 24：93 里有三个 24，余 21 落下 6 得 216，商 9，答案是 39。',
        sub: '936 ÷ 24 = 39',
        emp: ['答案是 39'],
        act(){ M.div.set(2, 5); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 试商与调商：商大了调小，商小了调大，每次只调 1
     --------------------------------------------------------------------- */
  const trial = {
    sec: '#s-trial',
    beats: SIX,
    idle: '除数不是整十数怎么办？先看作整十数试商。点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '405 除以 15。除数 15 不是整十数，直接除不好算。',
        sub: '405 ÷ 15',
        emp: ['不是整十数'],
        act(){ M.trial.set(0, 0); } },

      { beat: '提问',
        say: '那就把 15 看成 20 来试，估一个商 3。这个 3 敢直接写上去吗？',
        sub: '15 看作 20，试商 3',
        emp: ['敢直接写上去吗'],
        act(){ M.trial.set(0, 1); } },

      { beat: '找关系',
        say: '先检验：20 乘 3 得 60，比被除数前两位 40 还大。商 3 太大了。',
        sub: '20 × 3 = 60 > 40，商大了',
        emp: ['商 3 太大了'],
        act(){ M.trial.set(0, 2); } },

      { beat: '算一算',
        say: '调小成 2：15 乘 2 得 30，30 比 40 小，商 2 正好，余 10。',
        sub: '15 × 2 = 30，商 2，余 10',
        emp: ['调小成 2'],
        act(){ M.trial.set(0, 3); } },

      { beat: '检验',
        say: '反过来的情形也要认：828 除以 27，看作 30 试商 2，30 乘 2 才 60，比 82 小太多，是商小了。',
        sub: '30 × 2 = 60 < 82，商小了',
        emp: ['商小了'],
        act(){ M.trial.set(2, 2); } },

      { beat: '迁移',
        say: '那就调大成 3：27 乘 3 得 81，比 82 小，商 3 正好，余 1。',
        sub: '27 × 3 = 81，商 3，余 1',
        emp: ['调大成 3'],
        act(){ M.trial.set(2, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 商的变化规律：同时变，商不变
     --------------------------------------------------------------------- */
  const rule = {
    sec: '#s-rule',
    beats: SIX,
    idle: '被除数和除数一起变，商会变吗？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '先看一道已经会算的：240 除以 16，16 乘 15 等于 240，所以商是 15。',
        sub: '240 ÷ 16 = 15',
        emp: ['商是 15'],
        act(){ M.rule.set(2, 0); } },

      { beat: '提问',
        say: '现在被除数和除数都乘 2，变成 480 除以 32。商会跟着变成 30 吗？',
        sub: '480 ÷ 32，商变不变？',
        emp: ['商会跟着变成 30 吗'],
        act(){ M.rule.set(2, 1); } },

      { beat: '找关系',
        say: '再同时除以 2，变成 120 除以 8。一个乘 2，一个除以 2，商都还是 15。',
        sub: '120 ÷ 8 = 15，商没变',
        emp: ['商都还是 15'],
        act(){ M.rule.set(2, 2); } },

      { beat: '算一算',
        say: '换个倍数：同时乘 4 得 960 除以 64，同时除以 4 得 60 除以 4，商还是 15。',
        sub: '960 ÷ 64 = 15；60 ÷ 4 = 15',
        emp: ['同时乘 4'],
        act(){ M.rule.set(4, 3); } },

      { beat: '检验',
        say: '回到乘 2 这一组验一遍：32 乘 15 等于 480，商确实是 15，没跟着翻倍。',
        sub: '32 × 15 = 480 ✓',
        emp: ['没跟着翻倍'],
        act(){ M.rule.set(2, 3); } },

      { beat: '迁移',
        say: '规则里为什么特意写 0 除外？同时乘 0，除数就变成 0，除以 0 是没有意义的。',
        sub: '除数不能是 0',
        emp: ['0 除外'],
        act(){ M.rule.set(1, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 解决问题：进一法还是去尾法，看剩下的那一点还有没有用
     --------------------------------------------------------------------- */
  const solve = {
    sec: '#s-solve',
    beats: SIX,
    idle: '25 人去划船，每条坐 4 人，要几条船？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '25 个同学去划船，每条船最多坐 4 人，问至少要租几条船。',
        sub: '25 人，每船 4 人，至少几条',
        emp: ['至少要租几条船'],
        act(){ M.solve.set(0, 0); } },

      { beat: '提问',
        say: '25 除以 4 得 6 余 1。商是 6，那答案就是 6 条船吗？',
        sub: '25 ÷ 4 = 6……1',
        emp: ['就是 6 条船吗'],
        act(){ M.solve.set(0, 1); } },

      { beat: '找关系',
        say: '看最后那一组：只剩 1 个人，可他也要坐船。6 条船装不下他。',
        sub: '最后 1 人也要有船坐',
        emp: ['只剩 1 个人'],
        act(){ M.solve.set(0, 2); } },

      { beat: '算一算',
        say: '所以要 6 加 1 等于 7 条。剩下的也要占一份，这就叫进一法。',
        sub: '6 + 1 = 7（进一法）',
        emp: ['进一法'],
        act(){ M.solve.set(0, 3); } },

      { beat: '检验',
        say: '换成裁布：25 米，一件用 3 米，8 件余 1 米。这 1 米做不成一件，只能舍掉。',
        sub: '25 ÷ 3 = 8……1（去尾法）',
        emp: ['做不成一件'],
        act(){ M.solve.set(1, 3); } },

      { beat: '迁移',
        say: '同样是余数，一个要加 1，一个要舍掉。就看剩下的那一点，还有没有用。',
        sub: '看余下的还有没有用',
        emp: ['还有没有用'],
        act(){ M.solve.set(3, 3); } }
    ]
  };

  window.NARR = Narrator.boot([oral, vertical, trial, rule, solve]);
})();
