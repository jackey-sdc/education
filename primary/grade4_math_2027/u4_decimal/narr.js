/* ==========================================================================
   第四单元 小数的意义和性质 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（5 处推翻：1 处意义只讲"十分之几" /
   1 处数位表只填表格 / 1 处读法只给读作 / 1 处性质只背"添 0 不变" /
   1 处大小比较只比位数）。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   本单元的一条主线：小数不是"带点的新数"，它是把 1 继续往下分出来的份数；
   数位、读法、性质、比大小，全都在讲**每一份有多大**。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 小数的意义：把 1 平均分成 10 份
     --------------------------------------------------------------------- */
  const meaning = {
    sec: '#s-meaning',
    beats: SIX,
    idle: '把 1 平均分成 10 份，涂几份就是几？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '把 1 平均分成 10 份，10 份全涂满，还是 1。',
        sub: '10 份全满 = 1',
        emp: ['还是 1'],
        act(){ M.meaning.set(10); } },

      { beat: '提问',
        say: '现在只涂 3 份。不满 1 个整的，该用什么数来表示？',
        sub: '只涂 3 份 = ?',
        emp: ['不满 1 个整的'],
        act(){ M.meaning.set(3); } },

      { beat: '找关系',
        say: '1 份就是十分之一，写成小数是 0.1。这就是小数的计数单位。',
        sub: '1 份 = 1/10 = 0.1',
        emp: ['0.1'],
        act(){ M.meaning.set(1); } },

      { beat: '算一算',
        say: '7 份就是 7 个 0.1，写作 0.7，读作零点七。',
        sub: '7/10 = 0.7',
        emp: ['7 个 0.1'],
        act(){ M.meaning.set(7); } },

      { beat: '检验',
        say: '回头看 3 份：3 个 0.1 是 0.3。看份数就知道十分位上写几。',
        sub: '3 份 → 0.3',
        emp: ['看份数就知道十分位上写几'],
        act(){ M.meaning.set(4); } },

      { beat: '迁移',
        say: '0.1 再往下分 10 份就是 0.01，再分是 0.001。相邻单位的进率是 10。',
        sub: '0.1 → 0.01 → 0.001（÷10）',
        emp: ['进率是 10'],
        act(){ M.meaning.set(5); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 数位顺序表：每一位站在哪儿
     --------------------------------------------------------------------- */
  const place = {
    sec: '#s-place',
    beats: SIX,
    idle: '3.205 每一位分别是什么位？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '3.205。先以小数点为界，拆成整数部分 3 和小数部分 205。',
        sub: '3 . 205',
        emp: ['小数点为界'],
        act(){ M.place.set('3.205', 0); } },

      { beat: '提问',
        say: '小数点右边那三位，谁站在哪一格？位置不一样，意思一样吗？',
        sub: '谁站在哪一格',
        emp: ['意思一样吗'],
        act(){ M.place.set('3.205', 1); } },

      { beat: '找关系',
        say: '填进数位表就清楚了：3 在个位，2 在十分位，0 在百分位，5 在千分位。',
        sub: '个位 3、十分位 2、百分位 0、千分位 5',
        emp: ['数位表'],
        act(){ M.place.set('3.205', 2); } },

      { beat: '算一算',
        say: '每一位都有自己的计数单位：十分位是 0.1，百分位 0.01，千分位 0.001。',
        sub: '0.1 / 0.01 / 0.001',
        emp: ['计数单位'],
        act(){ M.place.set('20.05', 2); } },

      { beat: '检验',
        say: '看 20.05：十分位上是 0，这个 0 得占住位置，不能省。',
        sub: '20.05 十分位是 0',
        emp: ['不能省'],
        act(){ M.place.set('0.40', 2); } },

      { beat: '迁移',
        say: '整数部分也一样：100.3 中间那两个 0 都在占位，一个都不能少。',
        sub: '100.3 中间的 0 不能丢',
        emp: ['一个都不能少'],
        act(){ M.place.set('100.3', 2); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 读法与写法
     --------------------------------------------------------------------- */
  const read = {
    sec: '#s-read',
    beats: SIX,
    idle: '3.205 怎么读？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '3.205。读小数要分两步：先读整数部分，再逐位读小数部分。',
        sub: '整数部分 + 小数部分',
        emp: ['逐位读'],
        act(){ M.read.set(0, 0); } },

      { beat: '提问',
        say: '小数部分能不能像整数那样说"二百零五"？还是另有读法？',
        sub: '小数部分怎么读？',
        emp: ['另有读法'],
        act(){ M.read.set(0, 1); } },

      { beat: '找关系',
        say: '整数部分按整数读作三；小数点读作点；小数部分一位一位读，是二零五。',
        sub: '三点二零五',
        emp: ['二零五'],
        act(){ M.read.set(0, 2); } },

      { beat: '算一算',
        say: '20.05 要格外小心：小数部分中间的 0 必须读出来，二十点零五。',
        sub: '20.05 → 二十点零五',
        emp: ['必须读出来'],
        act(){ M.read.set(1, 2); } },

      { beat: '检验',
        say: '0.50 按原数读是零点五零；化简成 0.5 才读零点五。读法和写法要一致。',
        sub: '0.50 → 零点五零',
        emp: ['零点五零'],
        act(){ M.read.set(2, 2); } },

      { beat: '迁移',
        say: '100.3 读作一百点三。整数部分的 0 照常读，小数部分只有一位。',
        sub: '100.3 → 一百点三',
        emp: ['一百点三'],
        act(){ M.read.set(3, 2); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 小数的性质：末尾添 0 去 0，大小不变
     --------------------------------------------------------------------- */
  const property = {
    sec: '#s-property',
    beats: SIX,
    idle: '0.5 和 0.50 一样大吗？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '0.5 和 0.50。位数不一样，它们是一样大，还是有一个更大？',
        sub: '0.5 与 0.50',
        emp: ['一样大'],
        act(){ M.prop.set(0, 0); } },

      { beat: '提问',
        say: '光看数字容易看花眼。有没有办法把它们摆到一起看？',
        sub: '怎么摆到一起看',
        emp: ['摆到一起看'],
        act(){ M.prop.set(0, 1); } },

      { beat: '找关系',
        say: '标到数轴上，两个点完全重合。位置相同，大小就相同。',
        sub: '数轴上两点重合',
        emp: ['完全重合'],
        act(){ M.prop.set(0, 2); } },

      { beat: '算一算',
        say: '所以末尾添 0 不改变大小：0.5 等于 0.50，1.2 也等于 1.200。',
        sub: '0.5 = 0.50，1.2 = 1.200',
        emp: ['末尾添 0 不改变大小'],
        act(){ M.prop.set(0, 3); } },

      { beat: '检验',
        say: '反过来也一样：0.50 去掉末尾的 0 变成 0.5，这一步叫化简。',
        sub: '0.50 → 0.5（化简）',
        emp: ['化简'],
        act(){ M.prop.set(2, 3); } },

      { beat: '迁移',
        say: '可 0.305 和 0.35 不相等：中间那个 0 占着百分位，去掉就变了。',
        sub: '0.305 ≠ 0.35',
        emp: ['不相等'],
        act(){ M.prop.set(3, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 大小比较 + 小数点移动
     --------------------------------------------------------------------- */
  const compare = {
    sec: '#s-compare',
    beats: SIX,
    idle: '0.5 和 0.48 谁大？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '0.5 和 0.48，谁大？整数部分都是 0，先放一边不看。',
        sub: '0.5 与 0.48',
        emp: ['谁大'],
        act(){ M.cmp.set(0, 0); } },

      { beat: '提问',
        say: '先看另一件事：小数点向右移一位，2.5 就变成 25，一下大了十倍。',
        sub: '2.5 → 25（×10）',
        emp: ['大了十倍'],
        act(){ M.move.set(1); } },

      { beat: '找关系',
        say: '所以比大小不能数位数。位数多不多不重要，要看每一位站在哪个位置。',
        sub: '比位置，不比位数',
        emp: ['不能数位数'],
        act(){ M.cmp.set(0, 1); } },

      { beat: '算一算',
        say: '整数部分相同，就比十分位：5 比 4 大，所以 0.5 大于 0.48。',
        sub: '十分位 5 > 4 → 0.5 > 0.48',
        emp: ['5 比 4 大'],
        act(){ M.cmp.set(0, 2); } },

      { beat: '检验',
        say: '再验一组：3.6 和 3.06。十分位 6 比 0 大，所以 3.6 更大。',
        sub: '3.6 > 3.06',
        emp: ['3.6 更大'],
        act(){ M.cmp.set(1, 2); } },

      { beat: '迁移',
        say: '1.09 和 1.9 呢？十分位 0 比 9 小，位数多的那个反而更小。',
        sub: '1.09 < 1.9',
        emp: ['位数多的那个反而更小'],
        act(){ M.cmp.set(2, 2); } }
    ]
  };

  window.NARR = Narrator.boot([meaning, place, read, property, compare]);
})();
