/* ==========================================================================
   第三单元 三角形 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（4 处推翻：1 处稳定性只给结论 /
   1 处三边关系只让背"任意两边之和大于第三边" / 1 处内角和直接给 180 /
   1 处画高只讲"从顶点作垂线"）。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   本单元的一条主线：三角形的所有结论，都来自"三条边一旦定住，
   形状就定住"。稳定性、三边关系、内角和、高，都是这句话的不同侧面。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 三角形的稳定性
     --------------------------------------------------------------------- */
  const feature = {
    sec: '#s-feature',
    beats: SIX,
    idle: '三角形和四边形，各推一下会怎样？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '左边是三角形框架，右边是四边形框架，都只用几根小棒搭成。',
        sub: '三角形 vs 四边形',
        emp: ['几根小棒搭成'],
        act(){ M.feature.set(0, 0); } },

      { beat: '提问',
        say: '现在给两个框架施加同样大小的力，你觉得谁会变形？',
        sub: '同样推一推，谁变形？',
        emp: ['谁会变形'],
        act(){ M.feature.set(0, 1); } },

      { beat: '找关系',
        say: '结果很清楚：三角形纹丝不动，四边形一推就歪。差别就在边的条数。',
        sub: '三角形不动，四边形歪了',
        emp: ['一推就歪'],
        act(){ M.feature.set(1, 2); } },

      { beat: '算一算',
        say: '三角形三条边一定，三个角就跟着定死，一个角都改不了。',
        sub: '三边定 → 三角定',
        emp: ['定死'],
        act(){ M.feature.set(1, 3); } },

      { beat: '检验',
        say: '这就是稳定性。自行车三角架、房屋的人字梁，都是靠它加固的。',
        sub: '自行车三角架、人字梁',
        emp: ['稳定性'],
        act(){ M.feature.set(1, 4); } },

      { beat: '迁移',
        say: '四边形想稳，就加一根斜撑，把它切成两个三角形，立刻就稳住了。',
        sub: '四边形 + 斜撑 = 两个三角形',
        emp: ['一根斜撑'],
        act(){ M.feature.set(0, 5); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 三边关系
     --------------------------------------------------------------------- */
  const three = {
    sec: '#s-three',
    beats: SIX,
    idle: '三根小棒能不能围成三角形？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '三根小棒，6 厘米、5 厘米、8 厘米。它们能围成一个三角形吗？',
        sub: '6、5、8 能围成吗',
        emp: ['能围成一个三角形吗'],
        act(){ M.three.set(6, 5, 8, 0); } },

      { beat: '提问',
        say: '先别急着信答案。三条边摆在眼前，凭什么就能围上？',
        sub: '凭什么能围上',
        emp: ['凭什么'],
        act(){ M.three.set(6, 5, 8, 1); } },

      { beat: '找关系',
        say: '把最长的那根换成 12 就围不上了：6 加 5 只有 11，短了一截。',
        sub: '6 + 5 = 11 < 12，围不成',
        emp: ['短了一截'],
        act(){ M.three.set(6, 5, 12, 0); } },

      { beat: '算一算',
        say: '换成 3、4、5：3 加 4 得 7 比 5 大，任意两边之和都大于第三边。',
        sub: '3 + 4 > 5，能围成',
        emp: ['任意两边之和都大于第三边'],
        act(){ M.three.set(3, 4, 5, 0); } },

      { beat: '检验',
        say: '再看 5、5、10：两边之和正好等于第三边，三根拉成一条直线，围不成。',
        sub: '5 + 5 = 10，围不成',
        emp: ['正好等于'],
        act(){ M.three.set(5, 5, 10, 0); } },

      { beat: '迁移',
        say: '所以判断只用一个动作：最短的两边加起来，不超过最长的那边就围不成。',
        sub: '最短两边之和 > 最长边',
        emp: ['不超过最长的那边'],
        act(){ M.three.set(6, 8, 15, 0); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 三角形的分类：按角看最大的角，按边看是否等长
     --------------------------------------------------------------------- */
  const cls = {
    sec: '#s-cls',
    beats: SIX,
    idle: '同一个三角形，可以按角叫，也可以按边叫。点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '一个三角形，两个底角都是 60 度，顶角也是 60 度，三个角一样大。',
        sub: '60°、60°、60°',
        emp: ['三个角一样大'],
        act(){ M.cls.set(60, 60); } },

      { beat: '提问',
        say: '换一组：70 度、50 度，顶角 60 度。这个三角形该怎么叫？',
        sub: '70°、50°、60°',
        emp: ['该怎么叫'],
        act(){ M.cls.set(70, 50); } },

      { beat: '找关系',
        say: '按角分只看最大的那个角。顶角变成 90 度，就是直角三角形。',
        sub: '有一个角是 90° → 直角三角形',
        emp: ['直角三角形'],
        act(){ M.cls.set(90, 45); } },

      { beat: '算一算',
        say: '顶角 120 度，比直角还大，这是钝角三角形。三个角里只能有一个这么大。',
        sub: '有一个角 > 90° → 钝角三角形',
        emp: ['钝角三角形'],
        act(){ M.cls.set(120, 30); } },

      { beat: '检验',
        say: '换个标准按边看：两个底角都是 50 度，它们对的腰就相等，是等腰。',
        sub: '两角相等 → 两腰相等',
        emp: ['等腰'],
        act(){ M.cls.set(50, 50); } },

      { beat: '迁移',
        say: '底角 80 度和 20 度，三条边都不相等，那叫不等边三角形。',
        sub: '三边都不等 → 不等边三角形',
        emp: ['不等边三角形'],
        act(){ M.cls.set(80, 20); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 内角和：把三个角撕下来拼成一条直线
     --------------------------------------------------------------------- */
  const ang = {
    sec: '#s-ang',
    beats: SIX,
    idle: '三个角加起来是多少？撕下来拼一拼就知道。点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '这个三角形，三个内角分别是 52 度、68 度、60 度。',
        sub: '52°、68°、60°',
        emp: ['52 度、68 度、60 度'],
        act(){ M.ang.set(0); } },

      { beat: '提问',
        say: '三个角大小都不一样。它们的和会不会跟三角形的大小有关？',
        sub: '和会变吗？',
        emp: ['有关'],
        act(){ M.ang.set(1); } },

      { beat: '找关系',
        say: '把 52 度那个角撕下来放到一边，再把 68 度紧挨着拼上去，合起来 120 度。',
        sub: '52° + 68° = 120°',
        emp: ['合起来 120 度'],
        act(){ M.ang.set(2); } },

      { beat: '算一算',
        say: '三个角拼在一起，正好是一条直线，也就是平角 180 度。',
        sub: '52 + 68 + 60 = 180',
        emp: ['平角 180 度'],
        act(){ M.ang.set(3); } },

      { beat: '检验',
        say: '回头看清楚：每个角都是被完整撕下来的，一点没丢，也没有重叠。',
        sub: '不丢、不重、正好拼满',
        emp: ['一点没丢'],
        act(){ M.ang.set(2); } },

      { beat: '迁移',
        say: '所以任意三角形的内角和都是 180 度，跟它多大、什么形状都无关。',
        sub: '内角和 = 180°，与形状无关',
        emp: ['都是 180 度'],
        act(){ M.ang.set(0); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 画高：从顶点向对边所在直线作垂线
     --------------------------------------------------------------------- */
  const height = {
    sec: '#s-height',
    beats: SIX,
    idle: '高到底画在哪？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '这是一个锐角三角形。高是什么？先看它的三个顶点和三条边。',
        sub: '锐角三角形',
        emp: ['高是什么'],
        act(){ M.height.set(0, 0); } },

      { beat: '提问',
        say: '从顶点 A 往对面那条边画，画一条什么样的线才叫高？',
        sub: '画一条什么线才叫高',
        emp: ['什么样的线'],
        act(){ M.height.set(0, 1); } },

      { beat: '找关系',
        say: '要画垂线。从 A 向对边 BC 作垂线，顶点到垂足这条垂线段就是一条高。',
        sub: 'A → BC 的垂线段',
        emp: ['垂线段'],
        act(){ M.height.set(0, 3); } },

      { beat: '算一算',
        say: '三条都画出来：每个顶点都能作一条高，所以三角形有三条高。',
        sub: '3 个顶点 → 3 条高',
        emp: ['有三条高'],
        act(){ M.height.set(1, 3); } },

      { beat: '检验',
        say: '钝角三角形更特别：有两条高落在边的延长线上，得先把边延长再画。',
        sub: '两条高在延长线上',
        emp: ['延长线上'],
        act(){ M.height.set(2, 3); } },

      { beat: '迁移',
        say: '回到锐角三角形。高一定和底边垂直，画完别忘了标上直角符号。',
        sub: '高 ⊥ 底边，标直角符号',
        emp: ['直角符号'],
        act(){ M.height.set(0, 2); } }
    ]
  };

  window.NARR = Narrator.boot([feature, three, cls, ang, height]);
})();
