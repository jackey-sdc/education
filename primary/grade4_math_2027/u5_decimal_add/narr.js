/* ==========================================================================
   第五单元 小数的加法和减法 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（4 处推翻：1 处加减法只讲"对齐小数点" /
   1 处减法不讲退位 / 1 处对齐只给正确做法 / 1 处混合运算照搬整数顺序不解释）。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   本单元的一条主线：小数加减法和整数加减法是同一件事——
   只有**相同计数单位**的数才能直接相加减，所以必须小数点对齐。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 小数加法
     --------------------------------------------------------------------- */
  const add = {
    sec: '#s-add',
    beats: SIX,
    idle: '3.2 加 2.8，竖式怎么列？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '3.2 加 2.8。先把两个数上下摆好，列成竖式。',
        sub: '3.2 + 2.8',
        emp: ['列成竖式'],
        act(){ M.add.set(0, 0); } },

      { beat: '提问',
        say: '摆的时候，是末位对齐，还是小数点对齐？两种摆法结果一样吗？',
        sub: '末位对齐 还是 小数点对齐',
        emp: ['结果一样吗'],
        act(){ M.add.set(0, 1); } },

      { beat: '找关系',
        say: '必须小数点对齐。小数点对齐了，每一位的计数单位才一样，才能直接相加。',
        sub: '对齐小数点 = 对齐计数单位',
        emp: ['小数点对齐'],
        act(){ M.add.set(2, 1); } },

      { beat: '算一算',
        say: '位数不同的时候补 0：12.5 加 7.35，把 12.5 看成 12.50 再算。',
        sub: '12.5 → 12.50，再相加',
        emp: ['补 0'],
        act(){ M.add.set(2, 3); } },

      { beat: '检验',
        say: '12.50 加 7.35 得 19.85。验一下：19.85 减 7.35 正好回到 12.5。',
        sub: '12.50 + 7.35 = 19.85 ✓',
        emp: ['19.85 减 7.35'],
        act(){ M.add.set(3, 3); } },

      { beat: '迁移',
        say: '再看 5.6 加 3.7：十分位 6 加 7 得 13，满十进一，结果是 9.3。',
        sub: '5.6 + 3.7 = 9.3',
        emp: ['满十进一'],
        act(){ M.add.set(1, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 小数减法
     --------------------------------------------------------------------- */
  const sub = {
    sec: '#s-sub',
    beats: SIX,
    idle: '5 减 3.68 怎么减？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '5 减 3.68。一个整数，一个小数，位数差得挺多。',
        sub: '5 − 3.68',
        emp: ['位数差得挺多'],
        act(){ M.sub.set(1, 0); } },

      { beat: '提问',
        say: '整数 5 后面没有小数位，先补成 5.00；3.68 里的 8 在百分位上，拿什么去减它？',
        sub: '拿什么减百分位',
        emp: ['拿什么去减'],
        act(){ M.sub.set(1, 1); } },

      { beat: '找关系',
        say: '把 5 看成 5.00。整数后面可以补小数点和 0，大小不变，位就齐了。',
        sub: '5 = 5.00',
        emp: ['看成 5.00'],
        act(){ M.sub.set(1, 2); } },

      { beat: '算一算',
        say: '百分位 0 减 8 不够，向前一位借 1 当 10，十减八得二，继续往前借。',
        sub: '不够减就借 1 当 10',
        emp: ['借 1 当 10'],
        act(){ M.sub.set(1, 3); } },

      { beat: '检验',
        say: '结果是 1.32。验一下：1.32 加 3.68 正好等于 5，减对了。',
        sub: '5 − 3.68 = 1.32 ✓',
        emp: ['正好等于 5'],
        act(){ M.sub.set(0, 3); } },

      { beat: '迁移',
        say: '再看 20 减 0.35：20 看成 20.00，连续退位，得 19.65。',
        sub: '20 − 0.35 = 19.65',
        emp: ['连续退位'],
        act(){ M.sub.set(3, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 小数点对齐：两种列法一比，错在哪就看见了
     --------------------------------------------------------------------- */
  const align = {
    sec: '#s-align',
    beats: SIX,
    idle: '1.2 加 0.68，两种列法结果不同。点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '1.2 加 0.68。有人把末位对齐，2 和 8 挨着，算出来 1.80。',
        sub: '末位对齐 → 1.80',
        emp: ['1.80'],
        act(){ M.align.set(0); } },

      { beat: '提问',
        say: '可 2 和 8 这两个数挨在一起，它们的单位真的相同吗？',
        sub: '2 和 8 单位相同吗',
        emp: ['单位真的相同吗'],
        act(){ M.align.set(0); } },

      { beat: '找关系',
        say: '不同。2 站在十分位，单位是 0.1；8 站在百分位，单位是 0.01。',
        sub: '2 是 0.1，8 是 0.01',
        emp: ['0.1'],
        act(){ M.align.set(3); } },

      { beat: '算一算',
        say: '单位不同的数不能直接加减。把 1.2 补成 1.20，小数点对齐，才能加。',
        sub: '1.20 + 0.68',
        emp: ['不能直接加减'],
        act(){ M.align.set(1); } },

      { beat: '检验',
        say: '对齐后算得 1.88。验一下：0.68 加 1.88 等于 2.56，正是 1.2 加 0.68。',
        sub: '1.20 + 0.68 = 1.88 ✓',
        emp: ['1.88'],
        act(){ M.align.set(2); } },

      { beat: '迁移',
        say: '所以一句话：小数加减必须小数点对齐，因为只有相同数位才加减得起来。',
        sub: '小数点对齐 = 相同数位对齐',
        emp: ['必须小数点对齐'],
        act(){ M.align.set(1); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 小数加减混合运算
     --------------------------------------------------------------------- */
  const mixed = {
    sec: '#s-mixed',
    beats: SIX,
    idle: '3.6 加 0.4 乘 2.5，先算哪个？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '3.6 加 0.4 乘 2.5。小数混合运算，顺序和整数一样吗？',
        sub: '3.6 + 0.4 × 2.5',
        emp: ['顺序和整数一样吗'],
        act(){ M.mixed.set(0, -1); } },

      { beat: '提问',
        say: '先算 3.6 加 0.4 得 4，再乘 2.5 得 10。能这么算吗？',
        sub: '从左往右 → 10？',
        emp: ['能这么算吗'],
        act(){ M.mixed.set(0, 0); } },

      { beat: '找关系',
        say: '不行。先乘除后加减，这条规则小数照样管用，得先算 0.4 乘 2.5。',
        sub: '先乘除，后加减',
        emp: ['先乘除后加减'],
        act(){ M.mixed.set(0, 2); } },

      { beat: '算一算',
        say: '0.4 乘 2.5 得 1，3.6 加 1 得 4.6。顺序对了，答案才对。',
        sub: '0.4 × 2.5 = 1；3.6 + 1 = 4.6',
        emp: ['4.6'],
        act(){ M.mixed.set(1, 2); } },

      { beat: '检验',
        say: '有括号就先算括号：7.5 减 2.3 得 5.2，5.2 乘 2 得 10.4。',
        sub: '(7.5 − 2.3) × 2 = 10.4',
        emp: ['先算括号'],
        act(){ M.mixed.set(3, 2); } },

      { beat: '迁移',
        say: '最容易错的是 12.5 减 2.5 乘 4：一定先算乘，2.5 乘 4 得 10，结果 2.5。',
        sub: '12.5 − 2.5 × 4 = 2.5',
        emp: ['结果 2.5'],
        act(){ M.mixed.set(2, 2); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 运算律推广到小数
     --------------------------------------------------------------------- */
  const law = {
    sec: '#s-law',
    beats: SIX,
    idle: '整数凑整的那一套，小数也能用吗？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '0.7 加 3.9 再加 0.3。按顺序算也行，只是有点啰嗦。',
        sub: '0.7 + 3.9 + 0.3',
        emp: ['有点啰嗦'],
        act(){ M.law.set(0, -1); } },

      { beat: '提问',
        say: '0.7 和 0.3 加起来正好是 1。能不能先算这两个？',
        sub: '先算 0.7 + 0.3 行吗',
        emp: ['正好是 1'],
        act(){ M.law.set(0, 0); } },

      { beat: '找关系',
        say: '能。加法交换律和结合律对小数一样成立，位置可以换，分组也可以换。',
        sub: '(0.7 + 0.3) + 3.9',
        emp: ['一样成立'],
        act(){ M.law.set(0, 1); } },

      { beat: '算一算',
        say: '先算 0.7 加 0.3 得 1，1 加 3.9 得 4.9，一步就出来了。',
        sub: '1 + 3.9 = 4.9',
        emp: ['4.9'],
        act(){ M.law.set(0, 2); } },

      { beat: '检验',
        say: '乘法也一样：1.25 乘 3.6 乘 8，把 1.25 和 8 先乘，得 10 再乘 3.6。',
        sub: '1.25 × 8 × 3.6 = 36',
        emp: ['1.25 和 8 先乘'],
        act(){ M.law.set(1, 2); } },

      { beat: '迁移',
        say: '所以看到 2.5、1.25 这些数，先找它的搭档：2.5 找 4，1.25 找 8，凑整就快了。',
        sub: '2.5×4 = 10，1.25×8 = 10',
        emp: ['先找它的搭档'],
        act(){ M.law.set(3, 2); } }
    ]
  };

  window.NARR = Narrator.boot([add, sub, align, mixed, law]);
})();
