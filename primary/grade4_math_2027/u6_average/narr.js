/* ==========================================================================
   第六单元 平均数与条形统计图 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（4 处推翻：1 处平均数只给公式 /
   1 处公式不讲"为什么除以份数" / 1 处比较只报结论不给图 / 1 处综合实践当算术题做）。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   本单元的一条主线：平均数不是"算出来的一个数"，它是**移多补少之后的那个水平**；
   它的全部用处，在于让份数不同的两组数据能放在一起比。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 平均数的意义：移多补少
     --------------------------------------------------------------------- */
  const meaning = {
    sec: '#s-meaning',
    beats: SIX,
    idle: '三组不一样多，怎么用一个数代表它们？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '三组，分别是 4 个、5 个、6 个。三组多少不一样。',
        sub: '4、5、6',
        emp: ['多少不一样'],
        act(){ M.avg.set(3); } },

      { beat: '提问',
        say: '再添两组，变成 4、5、6、4、5。要让每组一样多，该怎么办？',
        sub: '4、5、6、4、5',
        emp: ['每组一样多'],
        act(){ M.avg.set(5); } },

      { beat: '找关系',
        say: '把 6 里的一个移给 4，三组就都成了 5 个。这一手叫移多补少。',
        sub: '6 给 4 一个 → 5、5、5',
        emp: ['移多补少'],
        act(){ M.avg.set(3); } },

      { beat: '算一算',
        say: '不搬也能算：六组一共 30 个，平均每组 30 除以 6 得 5。',
        sub: '30 ÷ 6 = 5',
        emp: ['30 除以 6'],
        act(){ M.avg.set(6); } },

      { beat: '检验',
        say: '四组一共 19 个，平均 4.75 个。平均数不一定是整数。',
        sub: '19 ÷ 4 = 4.75',
        emp: ['不一定是整数'],
        act(){ M.avg.set(4); } },

      { beat: '迁移',
        say: '五组平均 4.8 个，落在最小的 4 和最大的 6 之间，代表这组的整体水平。',
        sub: '4 < 4.8 < 6',
        emp: ['代表这组的整体水平'],
        act(){ M.avg.set(5); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 求平均数：总数 ÷ 份数
     --------------------------------------------------------------------- */
  const calc = {
    sec: '#s-calc',
    beats: SIX,
    idle: '80、90、70 的平均数怎么求？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '三组分别是 80、90、70。要求平均数，第一步该算什么？',
        sub: '80、90、70',
        emp: ['第一步该算什么'],
        act(){ M.calc.set(80, 90, 70); } },

      { beat: '提问',
        say: '先看一个特殊情形：三组都是 60，平均数还用算吗？',
        sub: '60、60、60',
        emp: ['还用算吗'],
        act(){ M.calc.set(60, 60, 60); } },

      { beat: '找关系',
        say: '一样多的时候，平均就是它自己。不一样时，先把总数合起来再分。',
        sub: '总数 ÷ 份数',
        emp: ['合起来再分'],
        act(){ M.calc.set(80, 90, 70); } },

      { beat: '算一算',
        say: '80 加 90 加 70 得 240，240 除以 3 份，平均 80。',
        sub: '240 ÷ 3 = 80',
        emp: ['240 除以 3'],
        act(){ M.calc.set(90, 90, 60); } },

      { beat: '检验',
        say: '再算 90、90、60：总数还是 240，除以 3 还是 80，方法对得上。',
        sub: '90+90+60 = 240，平均 80',
        emp: ['还是 80'],
        act(){ M.calc.set(70, 80, 90); } },

      { beat: '迁移',
        say: '换成 95、85、60，平均仍是 80。平均数不必等于其中任何一个数。',
        sub: '95+85+60 = 240，平均 80',
        emp: ['不必等于其中任何一个数'],
        act(){ M.calc.set(95, 85, 60); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 平均数的应用：份数相同比总数，份数不同比平均数
     --------------------------------------------------------------------- */
  const apply = {
    sec: '#s-apply',
    beats: SIX,
    idle: '两队植树，哪队植得多？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '两个小队植树，各植了 5 次。先看两边每次各植了多少棵。',
        sub: '甲队 5 次、乙队 5 次',
        emp: ['各植了 5 次'],
        act(){ M.apply.set(0, 0); } },

      { beat: '提问',
        say: '次数一样，是不是把总数加起来比一比就够了？',
        sub: '比总数就够了吗',
        emp: ['比一比就够了'],
        act(){ M.apply.set(0, 1); } },

      { beat: '找关系',
        say: '对。次数相同，份数就相同，总数多的那一队整体更多。',
        sub: '份数相同 → 比总数',
        emp: ['份数就相同'],
        act(){ M.apply.set(0, 2); } },

      { beat: '算一算',
        say: '甲队共 100 棵，乙队共 80 棵，甲队多。这一步只用了加法。',
        sub: '甲 100 > 乙 80',
        emp: ['甲队多'],
        act(){ M.apply.set(1, 0); } },

      { beat: '检验',
        say: '换成人数不同的情形：甲班 4 次共 120 张，乙班 3 次共 80 张，还能直接比吗？',
        sub: '4 次 120 张 vs 3 次 80 张',
        emp: ['还能直接比吗'],
        act(){ M.apply.set(1, 1); } },

      { beat: '迁移',
        say: '不能。次数不同就得比平均数：甲班 30 张，乙班约 26.7 张，甲班平均更多。',
        sub: '120÷4 = 30 > 80÷3 ≈ 26.7',
        emp: ['就得比平均数'],
        act(){ M.apply.set(1, 2); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 用平均数比较两组数据
     --------------------------------------------------------------------- */
  const cmp = {
    sec: '#s-cmp',
    beats: SIX,
    idle: '两个班每天读多久？看图比较。点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '复式条形统计图里是四（1）班和四（2）班五天的阅读时间。',
        sub: '两班各 5 天',
        emp: ['五天的阅读时间'],
        act(){ M.cmp.set(0); } },

      { beat: '提问',
        say: '周一四（1）班多，周三四（2）班多。只说某一天，能分出高低吗？',
        sub: '只看某一天行吗',
        emp: ['能分出高低吗'],
        act(){ M.cmp.set(0); } },

      { beat: '找关系',
        say: '不能。要比整体，就得先分别求总数：①班 70 分钟，②班 55 分钟。',
        sub: '①班 70，②班 55',
        emp: ['分别求总数'],
        act(){ M.cmp.set(1); } },

      { beat: '算一算',
        say: '再各除以 5 天：①班平均 14 分钟，②班平均 11 分钟。',
        sub: '70÷5 = 14，55÷5 = 11',
        emp: ['平均 14 分钟'],
        act(){ M.cmp.set(2); } },

      { beat: '检验',
        say: '把①班的平均线画上去，14 分钟这条线正好穿在柱子中间。',
        sub: '①班平均线 14 分',
        emp: ['平均线'],
        act(){ M.cmp.set(3); } },

      { beat: '迁移',
        say: '再把②班的 11 分线也画上。两条线一比，①班整体高出 3 分钟。',
        sub: '14 − 11 = 3 分',
        emp: ['整体高出 3 分钟'],
        act(){ M.cmp.set(4); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 综合实践：制定旅游计划
     --------------------------------------------------------------------- */
  const travel = {
    sec: '#s-travel',
    beats: SIX,
    idle: '30 人玩 3 天，怎么算人均花费？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '方案 A：30 人，3 天 2 晚。交通、住宿、门票、吃饭、其他，五项都列出来了。',
        sub: '30 人 · 3 天 2 晚',
        emp: ['五项都列出来了'],
        act(){ M.travel.set(0, 0); } },

      { beat: '提问',
        say: '住宿按人算还是按晚算？吃饭按人算还是按天算？单价不同，能直接乘人数吗？',
        sub: '住宿按人·晚，吃饭按人·天',
        emp: ['能直接乘人数吗'],
        act(){ M.travel.set(0, 2); } },

      { beat: '找关系',
        say: '不能。住宿乘的是人乘晚，吃饭乘的是人乘天，交通门票只乘人数。',
        sub: '各按各的单位算',
        emp: ['只乘人数'],
        act(){ M.travel.set(0, 3); } },

      { beat: '算一算',
        say: '方案 A 总费用 19800 元，除以 30 人，人均 660 元。',
        sub: '19800 ÷ 30 = 660 元',
        emp: ['人均 660 元'],
        act(){ M.travel.set(1, 3); } },

      { beat: '检验',
        say: '方案 B 用火车和民宿，总费用 13500 元，人均 450 元，比 A 省 210 元。',
        sub: '13500 ÷ 30 = 450 元',
        emp: ['人均 450 元'],
        act(){ M.travel.set(0, 4); } },

      { beat: '迁移',
        say: '比方案不能只看总钱数，要看人均。人均一算，贵的便宜的一目了然。',
        sub: '比方案 → 比人均',
        emp: ['要看人均'],
        act(){ M.travel.set(1, 4); } }
    ]
  };

  window.NARR = Narrator.boot([meaning, calc, apply, cmp, travel]);
})();
