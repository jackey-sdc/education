/* ==========================================================================
   第二单元 混合运算和运算律 —— 课程讲解脚本
   --------------------------------------------------------------------------
   三轮评审记录见 iterations.md（5 处推翻：1 处顺序只背口诀 / 1 处交换律
   只换位置不讲为什么能换 / 1 处分配律只给公式不讲面积 / 1 处结合律与交换律
   混着讲 / 1 处简便计算只教"凑"，不讲依据）。
   六拍骨架：读信息 → 提问 → 找关系 → 算一算 → 检验 → 迁移
   本单元的一条主线：运算律不是"允许我这么算"，而是"本来就相等"；
   交换、结合、分配，改的都是**分组方式**，不是数本身。
   ========================================================================== */
(function(){
  const M = window.MOD || {};
  const SIX = ['读信息', '提问', '找关系', '算一算', '检验', '迁移'];

  /* ---------------------------------------------------------------------
     ① 混合运算的顺序
     --------------------------------------------------------------------- */
  const order = {
    sec: '#s-order',
    beats: SIX,
    idle: '24 加 6 乘 5，先算哪一个？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '24 加 6 乘 5。乘法和加法摆在一起，到底先算哪一个？',
        sub: '24 + 6 × 5',
        emp: ['先算哪一个'],
        act(){ M.order.set(0, -1); } },

      { beat: '提问',
        say: '要是按从左往右算，24 加 6 得 30，30 乘 5 是 150。这样算对吗？',
        sub: '从左往右 → 150？',
        emp: ['这样算对吗'],
        act(){ M.order.set(0, 0); } },

      { beat: '找关系',
        say: '不对。乘法是几个相同加数合起来的简便写法，它比加法更紧，要先算。',
        sub: '6 × 5 = 30，24 + 30 = 54',
        emp: ['它比加法更紧'],
        act(){ M.order.set(0, 2); } },

      { beat: '算一算',
        say: '同级的情形要看顺序：25 乘 4 得 100，再除以 5 得 20，从左往右一步步来。',
        sub: '25 × 4 = 100，100 ÷ 5 = 20',
        emp: ['从左往右'],
        act(){ M.order.set(3, 1); } },

      { beat: '检验',
        say: '有括号就完全不一样：36 加 54 先算得 90，90 除以 6 得 15。括号里最优先。',
        sub: '(36 + 54) ÷ 6 = 15',
        emp: ['括号里最优先'],
        act(){ M.order.set(2, 2); } },

      { beat: '迁移',
        say: '三句话一起用：有括号先算括号，没括号先乘除后加减，同级从左往右。',
        sub: '括号 → 乘除 → 加减 → 同级向左',
        emp: ['同级从左往右'],
        act(){ M.order.set(3, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ② 加法的运算律：换位置、换分组，和都不变
     --------------------------------------------------------------------- */
  const addlaw = {
    sec: '#s-addlaw',
    beats: SIX,
    idle: '38 加 62，有更省事的算法吗？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '38 加 62。按顺序算也不难，可这两个数放在一起，是不是有点眼熟？',
        sub: '38 + 62',
        emp: ['有点眼熟'],
        act(){ M.addlaw.set(0, -1); } },

      { beat: '提问',
        say: '把两个加数换个位置，变成 62 加 38。允许这样换吗？和会不会变？',
        sub: '62 + 38，和会变吗',
        emp: ['和会不会变'],
        act(){ M.addlaw.set(0, 0); } },

      { beat: '找关系',
        say: '换位置和不变，这就是加法交换律。而且 62 加 38 正好凑整百，一步就出 100。',
        sub: 'a + b = b + a',
        emp: ['加法交换律'],
        act(){ M.addlaw.set(0, 2); } },

      { beat: '算一算',
        say: '三个数相加还能换分组：88 加 125 再加 12 不好算，改成 88 加 125 加 12。',
        sub: '(88 + 125) + 12 → 88 + (125 + 12)',
        emp: ['换分组'],
        act(){ M.addlaw.set(1, 1); } },

      { beat: '检验',
        say: '125 加 12 得 137，88 加 137 得 225。结果和原式一样，可算起来轻松多了。',
        sub: '88 + 137 = 225 ✓',
        emp: ['结果和原式一样'],
        act(){ M.addlaw.set(1, 3); } },

      { beat: '迁移',
        say: '减法也有类似的性质：连减两个数，等于一次减去它们的和。',
        sub: 'a − b − c = a − (b + c)',
        emp: ['等于一次减去它们的和'],
        act(){ M.addlaw.set(2, 3); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ③ 乘法的运算律：点子图转个方向，个数不变
     --------------------------------------------------------------------- */
  const mullaw = {
    sec: '#s-mullaw',
    beats: SIX,
    idle: '3 组每组 4 个，换成 4 组每组 3 个，个数会变吗？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '3 组，每组 4 个点子。一共多少个？3 乘 4 得 12。',
        sub: '3 × 4 = 12',
        emp: ['3 乘 4 得 12'],
        act(){ M.mullaw.set(3, 4, 0); } },

      { beat: '提问',
        say: '如果把图转个方向，变成 4 组、每组 3 个，点子数会变多还是变少？',
        sub: '4 组 × 3 个 = ?',
        emp: ['会变多还是变少'],
        act(){ M.mullaw.set(4, 3, 0); } },

      { beat: '找关系',
        say: '看，还是 12 个。两幅图只是横竖换了个方向，点子的个数根本没动。',
        sub: '还是 12 个',
        emp: ['根本没动'],
        act(){ M.mullaw.set(4, 3, 1); } },

      { beat: '算一算',
        say: '3 乘 4 和 4 乘 3 都得 12。两个因数换位置积不变，这是乘法交换律。',
        sub: 'a × b = b × a',
        emp: ['乘法交换律'],
        act(){ M.mullaw.set(3, 4, 1); } },

      { beat: '检验',
        say: '数一遍确认：第一幅横着每行 4 个共 3 行，第二幅每行 3 个共 4 行，都是 12。',
        sub: '4×3 与 3×4 都是 12',
        emp: ['都是 12'],
        act(){ M.mullaw.set(3, 4, 2); } },

      { beat: '迁移',
        say: '三个数连乘还能换分组：先乘前两个或先乘后两个，积都一样。',
        sub: '(a × b) × c = a × (b × c)',
        emp: ['积都一样'],
        act(){ M.mullaw.set(5, 2, 2); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ④ 乘法分配律：一块长方形切成两块
     --------------------------------------------------------------------- */
  const distrib = {
    sec: '#s-distrib',
    beats: SIX,
    idle: '一块长方形，能有两种算法吗？点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '这一整块长方形，宽是 c，长被分成 a 和 b 两段。整块面积怎么求？',
        sub: '长 = a + b，宽 = c',
        emp: ['整块面积怎么求'],
        act(){ M.distrib.set(60, 0); } },

      { beat: '提问',
        say: '最直接的想法是先把长加起来，再乘宽。可还有别的算法吗？',
        sub: '(a + b) × c',
        emp: ['还有别的算法吗'],
        act(){ M.distrib.set(60, 1); } },

      { beat: '找关系',
        say: '沿着那条竖线切一刀，分成两块。两块分别是 a 乘 c 和 b 乘 c。',
        sub: 'a × c 与 b × c',
        emp: ['切一刀'],
        act(){ M.distrib.set(60, 2); } },

      { beat: '算一算',
        say: '两块加起来就是整块。所以 a 加 b 的和乘 c，等于分别乘 c 再相加。',
        sub: '(a+b)×c = a×c + b×c',
        emp: ['分别乘 c 再相加'],
        act(){ M.distrib.set(60, 3); } },

      { beat: '检验',
        say: '换个分法再验一遍：长分成 30 和 70 两段。两块面积变了，加起来仍是整块。',
        sub: '换个分法，结论一样',
        emp: ['加起来仍是整块'],
        act(){ M.distrib.set(30, 3); } },

      { beat: '迁移',
        say: '反过来更常用：25 乘 37 加 25 乘 63，两项都有 25，提出来就是 25 乘 100。',
        sub: '25 × (37 + 63) = 2500',
        emp: ['提出来'],
        act(){ M.distrib.set(60, 3); M.distrib2.set(6); } }
    ]
  };

  /* ---------------------------------------------------------------------
     ⑤ 简便计算：先找能凑整的数对，每一步都要说清依据
     --------------------------------------------------------------------- */
  const simple = {
    sec: '#s-simple',
    beats: SIX,
    idle: '125 乘 32 乘 25，硬算要算半天。点「开始讲解」。',
    lock: [],
    steps: [
      { beat: '读信息',
        say: '125 乘 32 乘 25。三个数连乘，硬算也能算出来，但有没有更快的路？',
        sub: '125 × 32 × 25',
        emp: ['更快的路'],
        act(){ M.simple.set(0, -1); } },

      { beat: '提问',
        say: '看见 125 和 25，你应该想到两个老朋友。想想是哪两个数？',
        sub: '125 和 25 的好朋友是谁',
        emp: ['两个老朋友'],
        act(){ M.simple.set(0, 0); } },

      { beat: '找关系',
        say: '125 乘 8 得 1000，25 乘 4 得 100。正好 32 能拆成 8 乘 4。',
        sub: '32 = 8 × 4',
        emp: ['32 能拆成 8 乘 4'],
        act(){ M.simple.set(0, 1); } },

      { beat: '算一算',
        say: '用结合律分成两组：125 乘 8 一组，4 乘 25 一组，分别算再相乘。',
        sub: '(125 × 8) × (4 × 25)',
        emp: ['分成两组'],
        act(){ M.simple.set(0, 2); } },

      { beat: '检验',
        say: '1000 乘 100 得 100000。回头验：125 乘 32 是 4000，4000 乘 25 正好十万。',
        sub: '1000 × 100 = 100000 ✓',
        emp: ['正好十万'],
        act(){ M.simple.set(0, 3); } },

      { beat: '迁移',
        say: '再看 99 乘 25 加 25。最后那个 25 其实是 1 乘 25，凑成 100 个 25，得 2500。',
        sub: '(99 + 1) × 25 = 2500',
        emp: ['其实是 1 乘 25'],
        act(){ M.simple.set(1, 3); } }
    ]
  };

  window.NARR = Narrator.boot([order, addlaw, mullaw, distrib, simple]);
})();
